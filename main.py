def PREF_self_test_function_naming() -> None:
    """Verify function naming, duplicate definitions, translation consistency, and static call references."""
    source = Path(__file__).read_text(encoding="utf-8")
    tree = ast.parse(source, filename=__file__)
    function_nodes = [node for node in ast.walk(tree) if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))]
    names = [node.name for node in function_nodes]
    PREF_self_test_check(len(function_nodes) >= 100, "self-test suite has expanded beyond the original function set")
    PREF_self_test_check(all(name.startswith("PREF_") for name in names), "all functions use PREF_ namespace")
    PREF_self_test_check(len(names) == len(set(names)), "no duplicate function definitions")
    PREF_self_test_check(not any(isinstance(node, ast.Assert) for node in ast.walk(tree)), "production self-tests do not rely on assert statements")

    translation_assignment = next(
        node for node in tree.body
        if isinstance(node, ast.AnnAssign)
        and isinstance(node.target, ast.Name)
        and node.target.id == "PREF_TRANSLATIONS"
    )
    translations = ast.literal_eval(translation_assignment.value)
    PREF_self_test_check(set(translations) == {"ita", "eng"}, "supported language set is canonical")
    PREF_self_test_check(set(translations["ita"]) == set(translations["eng"]), "Italian/English translation keys are identical")
    PREF_self_test_check(all(isinstance(text, str) and text for lang in translations.values() for text in lang.values()), "all translation values are non-empty strings")

    literal_translation_keys = {
        node.args[0].value
        for node in ast.walk(tree)
        if isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == "PREF_translate"
        and node.args
        and isinstance(node.args[0], ast.Constant)
        and isinstance(node.args[0].value, str)
    }
    PREF_self_test_check(literal_translation_keys <= set(translations["ita"]), "all literal translation calls have defined keys")

    defined = set(names)
    direct_pref_calls = {
        node.func.id
        for node in ast.walk(tree)
        if isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id.startswith("PREF_")
    }
    PREF_self_test_check(direct_pref_calls <= defined, "all direct PREF_ calls resolve to defined functions")


