def PREF_recover_uncommitted_tail(
    workspace: str,
    manifest: dict[str, Any],
    public_key: bytes,
    signing_seed: bytes,
) -> str:
    """Adopt valid complete tail blocks and truncate only one incomplete final frame."""
    segment = manifest["segments"][-1]
    path = os.path.join(workspace, *segment["file"].split("/"))
    committed_offset = segment["committed_offset"]
    current_size = os.path.getsize(path)
    if current_size < committed_offset:
        raise RuntimeError(PREF_translate("err_recover_segment_shorter"))
    if current_size == committed_offset:
        return "none"

    previous_hash = manifest["last_chain_hash"]
    expected_number = manifest["next_operation_number"]
    adopted_count = 0
    adopted_last_hash = previous_hash
    truncate_to: int | None = None

    try:
        with open(path, "rb") as source:
            source.seek(committed_offset)
            cursor = committed_offset
            while cursor < current_size:
                frame_start = cursor
                raw_line = source.readline(PREF_MAX_BLOCK_BYTES + 1)
                if not raw_line:
                    break
                cursor += len(raw_line)
                if len(raw_line) > PREF_MAX_BLOCK_BYTES:
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                if not raw_line.endswith(b"\n"):
                    truncate_to = frame_start
                    break
                try:
                    block = json.loads(raw_line[:-1].decode("utf-8"))
                except (UnicodeDecodeError, json.JSONDecodeError) as exc:
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid")) from exc
                if not isinstance(block, dict):
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                if block.get("operation_number") != expected_number:
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                if not PREF_verify_block(
                    block,
                    previous_hash,
                    public_key,
                    manifest["program_hash"],
                    manifest["runtime_fingerprint"],
                ):
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                adopted_count += 1
                if segment["rows"] + adopted_count > PREF_MAX_ROWS_PER_SEGMENT:
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                previous_hash = block["chain_hash"]
                adopted_last_hash = previous_hash
                expected_number += 1
            if source.read(1):
                raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
    except OSError as exc:
        raise RuntimeError(PREF_translate("err_recover_tail_inspect")) from exc

    if truncate_to is not None:
        try:
            with open(path, "rb+") as target:
                target.truncate(truncate_to)
                target.flush()
                os.fsync(target.fileno())
        except OSError as exc:
            raise RuntimeError(PREF_translate("err_recover_tail_truncate")) from exc
        current_size = truncate_to

    if adopted_count == 0:
        if truncate_to is not None:
            return "truncated"
        raise RuntimeError(PREF_translate("err_recover_tail_invalid"))

    manifest["operation_count"] += adopted_count
    manifest["next_operation_number"] += adopted_count
    manifest["last_chain_hash"] = adopted_last_hash
    segment["rows"] += adopted_count
    segment["committed_offset"] = current_size
    if segment["rows"] == PREF_MAX_ROWS_PER_SEGMENT:
        segment["sealed"] = True
        segment["sha256"] = PREF_hash_file_streaming(path)

    signed_manifest = PREF_sign_manifest(manifest, signing_seed)
    PREF_write_atomic(PREF_manifest_path(workspace), PREF_canonical_json(signed_manifest) + b"\n")
    manifest.clear()
    manifest.update(signed_manifest)
    return "adopted" if truncate_to is None else "adopted_truncated"


def PREF_create_next_segment(workspace: str, manifest: dict[str, Any]) -> dict[str, Any]:
    """Create the next append segment atomically after the current one is sealed."""
    current_number = manifest["current_segment"]
    if manifest["segments"][-1]["rows"] < PREF_MAX_ROWS_PER_SEGMENT:
        raise RuntimeError(PREF_translate("err_segment_not_full"))
    next_number = current_number + 1
    path = PREF_segment_path(workspace, next_number)
    os.makedirs(PREF_segments_path(workspace), exist_ok=True)
    with open(path, "xb"):
        pass
    PREF_set_private_permissions(path)
    PREF_sync_directory(PREF_segments_path(workspace))
    segment = {
        "segment_number": next_number,
        "file": f"{PREF_SEGMENT_DIRECTORY}/{next_number:012d}.nxsb",
        "rows": 0,
        "committed_offset": 0,
        "sealed": False,
        "sha256": None,
    }
    manifest["segments"].append(segment)
    manifest["current_segment"] = next_number
    return segment


