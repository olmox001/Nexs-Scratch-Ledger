def PREF_build_unsigned_manifest(logical_name: str, identity: dict[str, Any], public_key: bytes) -> dict[str, Any]:
    """Create the signed public manifest body using portable relative paths."""
    if not PREF_validate_workspace_name(logical_name):
        raise ValueError(PREF_translate("err_workspace_name_invalid"))
    if len(public_key) != 32:
        raise ValueError(PREF_translate("err_public_key_invalid"))
    ledger_id = secrets.token_hex(16)
    return {
        "format": PREF_PROTOCOL_NAME,
        "schema_version": PREF_SCHEMA_VERSION,
        "ledger_id": ledger_id,
        "logical_name": PREF_normalize_workspace_name(logical_name),
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "program_version": identity["program_version_hash"],
        "program_hash": identity["program_hash"],
        "runtime_fingerprint": identity["runtime_fingerprint"],
        "extensions": PREF_dataset_deep_copy(identity["extensions"]),
        "python_implementation": identity["python_implementation"],
        "python_version": identity["python_version"],
        "public_key_ed25519": PREF_base64_encode(public_key),
        "public_read_key": PREF_make_public_read_key(identity["program_hash"], identity["runtime_fingerprint"], ledger_id),
        "operation_count": 0,
        "next_operation_number": 1,
        "last_chain_hash": PREF_GENESIS_HASH,
        "current_segment": 1,
        "segments": [
            {
                "segment_number": 1,
                "file": f"{PREF_SEGMENT_DIRECTORY}/000000000001.nxsb",
                "rows": 0,
                "committed_offset": 0,
                "sealed": False,
                "sha256": None,
            }
        ],
        "credential_mode": "pending",
        "username_fingerprint": "pending",
        "manifest_signature": None,
    }


def PREF_manifest_unsigned_body(manifest: dict[str, Any]) -> dict[str, Any]:
    """Return the exact public manifest content covered by the signature."""
    body = dict(manifest)
    body.pop("manifest_signature", None)
    return body


def PREF_sign_manifest(manifest: dict[str, Any], seed: bytes) -> dict[str, Any]:
    """Attach an Ed25519 signature to the manifest and return a new dict."""
    signed = PREF_manifest_unsigned_body(manifest)
    signed["manifest_signature"] = PREF_sign_bytes(seed, PREF_canonical_json(signed))
    return signed


def PREF_verify_manifest_signature(manifest: dict[str, Any]) -> bytes:
    """Verify the manifest signature and return its embedded public key.

    This function is intentionally tolerant of extra/missing schema fields: the
    manifest signature covers the whole unsigned body, so a tampered manifest
    fails signature verification even before structural validation runs.
    """
    if not isinstance(manifest, dict):
        raise RuntimeError(PREF_translate("manifest_invalid"))
    try:
        public_key = PREF_base64_decode(manifest["public_key_ed25519"], 32)
        signature = manifest["manifest_signature"]
    except (KeyError, ValueError, TypeError) as exc:
        raise RuntimeError(PREF_translate("err_manifest_pubkey_malformed")) from exc

    if not isinstance(signature, str):
        raise RuntimeError(PREF_translate("err_manifest_signature_not_text"))
    if not PREF_verify_signature(public_key, PREF_canonical_json(PREF_manifest_unsigned_body(manifest)), signature):
        raise RuntimeError(PREF_translate("manifest_invalid"))
    return public_key


def PREF_validate_manifest_structure(manifest: dict[str, Any], logical_name: str) -> None:
    """Reject malformed, ambiguous, or path-traversing manifests before filesystem access."""
    if not isinstance(manifest, dict):
        raise RuntimeError(PREF_translate("manifest_invalid"))
    required = {
        "format", "schema_version", "ledger_id", "logical_name", "created_utc",
        "program_version", "program_hash", "runtime_fingerprint", "extensions",
        "python_implementation", "python_version", "public_key_ed25519",
        "public_read_key", "operation_count", "next_operation_number", "last_chain_hash",
        "current_segment", "segments", "credential_mode", "username_fingerprint",
        "manifest_signature",
    }
    if set(manifest) != required:
        raise RuntimeError(PREF_translate("err_manifest_field_set"))
    if manifest["format"] != PREF_PROTOCOL_NAME or manifest["schema_version"] != PREF_SCHEMA_VERSION:
        raise RuntimeError(PREF_translate("err_manifest_format"))
    normalized_name = PREF_normalize_workspace_name(logical_name)
    if manifest["logical_name"] != normalized_name or not PREF_validate_workspace_name(normalized_name):
        raise RuntimeError(PREF_translate("err_manifest_name_mismatch"))

    def PREF_require_sha256(value: Any, label: str) -> None:
        if not isinstance(value, str) or len(value) != 64:
            raise RuntimeError(PREF_translate_format("err_manifest_sha256", label=label))
        try:
            bytes.fromhex(value)
        except ValueError as exc:
            raise RuntimeError(PREF_translate_format("err_manifest_sha256", label=label)) from exc

    PREF_require_sha256(manifest["program_hash"], "program_hash")
    PREF_require_sha256(manifest["runtime_fingerprint"], "runtime_fingerprint")
    PREF_require_sha256(manifest["public_read_key"], "public_read_key")
    PREF_require_sha256(manifest["last_chain_hash"], "last_chain_hash")
    if not isinstance(manifest["ledger_id"], str) or len(manifest["ledger_id"]) != 32:
        raise RuntimeError(PREF_translate("err_manifest_ledger_id"))
    try:
        bytes.fromhex(manifest["ledger_id"])
    except ValueError as exc:
        raise RuntimeError(PREF_translate("err_manifest_ledger_id")) from exc
    try:
        created = datetime.fromisoformat(manifest["created_utc"])
    except (TypeError, ValueError) as exc:
        raise RuntimeError(PREF_translate("err_manifest_created")) from exc
    if created.tzinfo is None:
        raise RuntimeError(PREF_translate("err_manifest_created_naive"))
    if not isinstance(manifest["program_version"], str) or not manifest["program_version"]:
        raise RuntimeError(PREF_translate("err_manifest_program_version"))
    if not isinstance(manifest["python_implementation"], str) or not manifest["python_implementation"]:
        raise RuntimeError(PREF_translate("err_manifest_python_impl"))
    if not isinstance(manifest["python_version"], str) or not manifest["python_version"]:
        raise RuntimeError(PREF_translate("err_manifest_python_version"))
    if not isinstance(manifest["operation_count"], int) or type(manifest["operation_count"]) is not int or manifest["operation_count"] < 0:
        raise RuntimeError(PREF_translate("err_manifest_opcount"))
    if not isinstance(manifest["next_operation_number"], int) or type(manifest["next_operation_number"]) is not int or manifest["next_operation_number"] != manifest["operation_count"] + 1:
        raise RuntimeError(PREF_translate("err_manifest_counter_invariant"))
    if manifest["credential_mode"] not in {"generic", "user"}:
        raise RuntimeError(PREF_translate("err_manifest_cred_mode"))
    fingerprint = manifest["username_fingerprint"]
    if not isinstance(fingerprint, str):
        raise RuntimeError(PREF_translate("err_manifest_fingerprint"))
    if manifest["credential_mode"] == "generic":
        if fingerprint != "0":
            raise RuntimeError(PREF_translate("err_manifest_generic_fingerprint"))
    else:
        if len(fingerprint) != 64:
            raise RuntimeError(PREF_translate("err_manifest_user_fingerprint"))
        try:
            bytes.fromhex(fingerprint)
        except ValueError as exc:
            raise RuntimeError(PREF_translate("err_manifest_user_fingerprint")) from exc

    extensions = manifest["extensions"]
    if not isinstance(extensions, list) or len(extensions) > 256:
        raise RuntimeError(PREF_translate("err_manifest_ext_list"))
    for item in extensions:
        if not isinstance(item, dict) or set(item) != {"file", "sha256"}:
            raise RuntimeError(PREF_translate("err_manifest_ext_descriptor"))
        filename = item["file"]
        if not isinstance(filename, str) or os.path.isabs(filename) or ".." in Path(filename).parts or "\\" in filename:
            raise RuntimeError(PREF_translate("err_manifest_ext_path_unsafe"))
        if not filename.endswith(".py"):
            raise RuntimeError(PREF_translate("err_manifest_ext_not_python"))
        PREF_require_sha256(item["sha256"], "extension_hash")

    segments = manifest["segments"]
    if not isinstance(segments, list) or not segments or len(segments) > PREF_MAX_SEGMENTS:
        raise RuntimeError(PREF_translate("err_manifest_seg_list"))
    if manifest["current_segment"] != len(segments):
        raise RuntimeError(PREF_translate("err_manifest_current_seg"))
    total_rows = 0
    for expected_number, segment in enumerate(segments, 1):
        if not isinstance(segment, dict) or set(segment) != {"segment_number", "file", "rows", "committed_offset", "sealed", "sha256"}:
            raise RuntimeError(PREF_translate("err_manifest_seg_descriptor"))
        if segment["segment_number"] != expected_number:
            raise RuntimeError(PREF_translate("err_manifest_seg_numbering"))
        expected_file = f"{PREF_SEGMENT_DIRECTORY}/{expected_number:012d}.nxsb"
        if segment["file"] != expected_file:
            raise RuntimeError(PREF_translate("err_manifest_seg_path"))
        rows = segment["rows"]
        offset = segment["committed_offset"]
        if type(rows) is not int or rows < 0 or rows > PREF_MAX_ROWS_PER_SEGMENT:
            raise RuntimeError(PREF_translate("err_manifest_seg_rows"))
        if type(offset) is not int or offset < 0:
            raise RuntimeError(PREF_translate("err_manifest_seg_offset"))
        if type(segment["sealed"]) is not bool:
            raise RuntimeError(PREF_translate("err_manifest_seg_sealed_flag"))
        if segment["sealed"]:
            PREF_require_sha256(segment["sha256"], "sealed_segment_hash")
        elif segment["sha256"] is not None:
            raise RuntimeError(PREF_translate("err_manifest_seg_unsealed_hash"))
        total_rows += rows
    if total_rows != manifest["operation_count"]:
        raise RuntimeError(PREF_translate("err_manifest_seg_row_total"))


def PREF_create_workspace(
    logical_name: str,
    directory: str,
    credentials: dict[str, Any],
    identity: dict[str, Any],
    *,
    persist_anchor: bool = True,
) -> tuple[str, dict[str, Any], bytes]:
    """Create a new signed workspace; the private seed is returned only in memory.

    When persist_anchor is True (the default), a trust anchor is written so the
    workspace's public key is pinned from the moment of creation. When
    NEXS_REQUIRE_ANCHOR is set, any failure to persist the anchor aborts the
    creation so that TOFU is never silently accepted in hardened deployments.
    """
    PREF_validate_credentials(credentials)
    workspace = PREF_workspace_path(logical_name, directory)
    if os.path.lexists(workspace):
        raise FileExistsError(workspace)

    os.makedirs(workspace, mode=0o700 if os.name != "nt" else 0o777)
    try:
        os.makedirs(PREF_segments_path(workspace), exist_ok=False)
        os.makedirs(PREF_staging_path(workspace), exist_ok=False)
        segment_path = PREF_segment_path(workspace, 1)
        with open(segment_path, "xb"):
            pass
        PREF_set_private_permissions(segment_path)
        PREF_sync_directory(PREF_segments_path(workspace))
        PREF_sync_directory(PREF_staging_path(workspace))
        PREF_sync_directory(workspace)

        seed = PREF_derive_private_seed(credentials["username"], credentials["password"], identity["program_hash"])
        public_key = PREF_public_key_from_seed(seed)
        manifest = PREF_build_unsigned_manifest(logical_name, identity, public_key)
        manifest["credential_mode"] = "generic" if credentials["generic"] else "user"
        manifest["username_fingerprint"] = credentials["username_fingerprint"]
        manifest = PREF_sign_manifest(manifest, seed)
        PREF_write_atomic(PREF_manifest_path(workspace), PREF_canonical_json(manifest) + b"\n")
        PREF_set_private_permissions(PREF_manifest_path(workspace))

        if persist_anchor:
            try:
                anchor_path = PREF_persist_trust_anchor(logical_name, public_key)
                PREF_print_message("trust_anchor_created", anchor_path)
            except (OSError, RuntimeError, ValueError, TypeError) as exc:
                if PREF_explicit_anchor_required():
                    # Hardened mode: do not accept a workspace that cannot be pinned.
                    raise RuntimeError(PREF_translate_format("err_anchor_persist_required", detail=exc)) from exc
                PREF_print_message("trust_anchor_persist_failed", exc)

        return workspace, manifest, seed
    except (OSError, RuntimeError, ValueError, TypeError, KeyError):
        shutil.rmtree(workspace, ignore_errors=True)
        raise


def PREF_load_manifest(workspace: str, logical_name: str) -> tuple[dict[str, Any], bytes]:
    """Load and cryptographically verify a workspace manifest.

    Validation order (hardening):
      1. Parse the JSON.
      2. Verify the embedded Ed25519 signature over the unsigned body.
      3. Enforce the external trust anchor, when one exists for this workspace.
      4. Validate the structural schema.
      5. Verify the derived public read key.
    """
    PREF_safe_workspace_directory(workspace)
    try:
        with open(PREF_manifest_path(workspace), "rb") as source:
            raw = source.read(PREF_MAX_MANIFEST_BYTES + 1)
    except OSError as exc:
        raise RuntimeError(PREF_translate("err_manifest_read")) from exc
    if len(raw) > PREF_MAX_MANIFEST_BYTES:
        raise RuntimeError(PREF_translate("err_manifest_too_large"))
    try:
        manifest = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RuntimeError(PREF_translate("manifest_invalid")) from exc
    if not isinstance(manifest, dict):
        raise RuntimeError(PREF_translate("manifest_invalid"))

    public_key = PREF_verify_manifest_signature(manifest)
    PREF_enforce_trust_anchor(logical_name, public_key)
    PREF_validate_manifest_structure(manifest, logical_name)

    expected_read_key = PREF_make_public_read_key(
        manifest["program_hash"],
        manifest["runtime_fingerprint"],
        manifest["ledger_id"],
    )
    if not PREF_secure_compare(expected_read_key, manifest["public_read_key"]):
        raise RuntimeError(PREF_translate("err_manifest_read_key_mismatch"))
    return manifest, public_key


def PREF_authorize_workspace_write(
    manifest: dict[str, Any],
    identity: dict[str, Any],
    credentials: dict[str, Any],
    public_key: bytes,
) -> tuple[bool, bytes | None, str]:
    """Authenticate workspace credentials and permit writes only after exact identity checks.

    Returns (allowed, seed_or_None, reason). Reasons:
      - "authorized": write is permitted and a seed is returned.
      - "credential_mode_mismatch": non-blank credentials against a generic workspace.
      - "credentials_required": blank credentials against a user workspace.
      - "credentials_invalid": non-blank credentials that do not authenticate.
      - "version_mismatch": program/runtime fingerprint differs from the manifest.
      - "runtime_changed": program file changed since identity initialization.

    Wrong credentials never abort the program; the workspace is simply opened
    read-only, matching the documented security model.
    """
    PREF_validate_credentials(credentials)
    if not isinstance(public_key, bytes) or len(public_key) != 32:
        raise ValueError(PREF_translate("err_public_key_invalid"))

    workspace_mode = manifest["credential_mode"]
    supplied_generic = credentials["generic"]

    if workspace_mode == "generic":
        if not supplied_generic:
            return False, None, "credential_mode_mismatch"
    elif workspace_mode == "user":
        if supplied_generic:
            return False, None, "credentials_required"
    else:
        raise RuntimeError(PREF_translate("err_manifest_cred_mode"))

    historical_seed = PREF_derive_private_seed(
        credentials["username"],
        credentials["password"],
        manifest["program_hash"],
    )
    derived_public_key = PREF_public_key_from_seed(historical_seed)

    if workspace_mode == "generic":
        if manifest["username_fingerprint"] != "0":
            raise RuntimeError(PREF_translate("err_manifest_generic_fingerprint"))
    else:
        if not PREF_secure_compare(
            manifest["username_fingerprint"], credentials["username_fingerprint"]
        ):
            return False, None, "credentials_invalid"

    if not PREF_secure_compare_bytes(derived_public_key, public_key):
        return False, None, "credentials_invalid"

    same_program = PREF_hashes_equal(manifest["program_hash"], identity.get("program_hash"))
    same_runtime = PREF_hashes_equal(
        manifest["runtime_fingerprint"], identity.get("runtime_fingerprint")
    )
    if not (same_program and same_runtime):
        return False, None, "version_mismatch"

    try:
        PREF_verify_runtime_identity_unchanged(identity)
    except RuntimeError:
        return False, None, "runtime_changed"

    current_seed = PREF_derive_private_seed(
        credentials["username"],
        credentials["password"],
        identity["program_hash"],
    )
    if not PREF_secure_compare_bytes(PREF_public_key_from_seed(current_seed), public_key):
        return False, None, "credentials_invalid"
    return True, current_seed, "authorized"


