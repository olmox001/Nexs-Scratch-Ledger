def PREF_validate_credentials(credentials: dict[str, Any]) -> None:
    """Validate the credential descriptor contract used throughout the program.

    In addition to structural validation, this recomputes the SHA-256 fingerprint
    from the username (normalized) so that callers cannot pass a mismatched
    fingerprint and rely on a later check to catch it.
    """
    if not isinstance(credentials, dict):
        raise TypeError(PREF_translate("err_credentials_type"))
    required = {"username", "password", "generic", "username_fingerprint"}
    if set(credentials) != required:
        raise ValueError(PREF_translate("err_credentials_fields"))
    if not isinstance(credentials["username"], str) or not isinstance(credentials["password"], str):
        raise TypeError(PREF_translate("err_credentials_types"))
    if not isinstance(credentials["generic"], bool):
        raise TypeError(PREF_translate("err_credentials_generic_flag"))
    if not isinstance(credentials["username_fingerprint"], str):
        raise TypeError(PREF_translate("err_credentials_fingerprint_type"))
    if credentials["generic"]:
        if credentials["username"] or credentials["password"]:
            raise ValueError(PREF_translate("err_credentials_generic_nonempty"))
        if credentials["username_fingerprint"] != "0":
            raise ValueError(PREF_translate("err_credentials_generic_fp"))
    else:
        if not credentials["username"] or not credentials["password"]:
            raise ValueError(PREF_translate("err_credentials_user_empty"))
        if len(credentials["username_fingerprint"]) != 64:
            raise ValueError(PREF_translate("err_credentials_user_fp_len"))
        try:
            bytes.fromhex(credentials["username_fingerprint"])
        except ValueError as exc:
            raise ValueError(PREF_translate("err_credentials_user_fp_hex")) from exc
        expected_fingerprint = PREF_sha256_text(PREF_normalize_username(credentials["username"]))
        if not PREF_secure_compare(credentials["username_fingerprint"], expected_fingerprint):
            raise ValueError(PREF_translate("err_credentials_user_fp_mismatch"))


def PREF_collect_credentials() -> dict[str, Any]:
    """Read username and password (or generic mode) from the interactive session.

    Kept as a small named helper so PREF_main stays focused on orchestration
    and so the credential contract is testable in isolation. Blank username
    AND blank password select generic mode; any other mismatch is rejected
    with a localized error and re-prompted.
    """
    for _attempt in range(PREF_MAX_INPUT_ATTEMPTS):
        try:
            username = PREF_input(PREF_translate("username_prompt"))
        except EOFError as exc:
            raise RuntimeError(PREF_translate("err_credentials_input_eof")) from exc
        try:
            password = PREF_getpass(PREF_translate("password_prompt"))
        except EOFError as exc:
            raise RuntimeError(PREF_translate("err_credentials_input_eof")) from exc
        username_stripped = username.strip()
        if not username_stripped and not password:
            return {
                "username": "",
                "password": "",
                "generic": True,
                "username_fingerprint": "0",
            }
        if username_stripped and password:
            normalized = PREF_normalize_username(username)
            if len(normalized) > PREF_MAX_USERNAME_CHARS:
                PREF_print(PREF_translate("credentials_partial"))
                continue
            if len(password) > PREF_MAX_PASSWORD_CHARS:
                PREF_print(PREF_translate("credentials_partial"))
                continue
            return {
                "username": username,
                "password": password,
                "generic": False,
                "username_fingerprint": PREF_sha256_text(normalized),
            }
        PREF_print(PREF_translate("credentials_partial"))
    raise RuntimeError(PREF_translate("err_credentials_limit"))


def PREF_scan_workspace_logical_name(path: str) -> str:
    """Read only the display name from a manifest; final trust is checked later."""
    try:
        with open(PREF_manifest_path(path), "rb") as source:
            raw = source.read(PREF_MAX_MANIFEST_BYTES)
        manifest = json.loads(raw.decode("utf-8"))
        name = manifest.get("logical_name")
        if isinstance(name, str) and name:
            return name
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        pass
    return os.path.basename(path)


def PREF_list_workspaces(directory: str = ".") -> list[str]:
    """List logical workspace names found in the current directory."""
    result: list[str] = []
    try:
        for entry in os.scandir(directory):
            if not entry.is_dir() or entry.is_symlink():
                continue
            if not entry.name.endswith(f".{PREF_FILE_EXTENSION}"):
                continue
            logical_name = PREF_scan_workspace_logical_name(entry.path)
            if not PREF_validate_workspace_name(logical_name):
                continue
            if entry.name != os.path.basename(PREF_physical_workspace_name(logical_name)):
                continue
            result.append(logical_name)
    except OSError as exc:
        raise RuntimeError(PREF_translate_format("err_workspace_list_dir", directory=directory)) from exc
    return sorted(result)


def PREF_generate_temporary_workspace_name() -> str:
    """Generate a safe temporary logical workspace identifier."""
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S_%f")
    return f"temporary_{timestamp}_{secrets.token_hex(8)}"


def PREF_choose_workspace(
    credentials: dict[str, Any],
    identity: dict[str, Any],
) -> tuple[str, bool]:
    """Create or load a workspace, with temporary mode for unsaved sessions."""
    create_or_load = PREF_confirm("workspace_question")
    current_directory = os.path.abspath(".")

    if not create_or_load:
        logical_name = PREF_generate_temporary_workspace_name()
        workspace, manifest, seed = PREF_create_workspace(
            logical_name,
            tempfile.gettempdir(),
            credentials,
            identity,
            persist_anchor=False,
        )
        del manifest, seed
        PREF_print(PREF_translate("workspace_temporary"), workspace)
        return workspace, True

    names = PREF_list_workspaces(current_directory)
    if names:
        PREF_print(PREF_translate("workspace_list"))
        for name in names:
            PREF_print(f"  - {name}")
    else:
        PREF_print(PREF_translate("workspace_none"))

    for _attempt in range(PREF_MAX_INPUT_ATTEMPTS):
        try:
            logical_name = PREF_normalize_workspace_name(PREF_input(PREF_translate("workspace_name_prompt")))
        except EOFError as exc:
            raise RuntimeError(PREF_translate("err_workspace_eof")) from exc
        if not PREF_validate_workspace_name(logical_name):
            PREF_print(PREF_translate("workspace_invalid_name"))
            continue
        workspace = PREF_workspace_path(logical_name, current_directory)
        if os.path.exists(workspace):
            PREF_print(PREF_translate("workspace_loaded"), workspace)
            return workspace, False
        try:
            workspace, manifest, seed = PREF_create_workspace(logical_name, current_directory, credentials, identity)
            del manifest, seed
            PREF_print(PREF_translate("workspace_created"), workspace)
            return workspace, False
        except FileExistsError:
            PREF_print(PREF_translate("workspace_exists"))
    raise RuntimeError(PREF_translate("err_workspace_selection_limit"))


def PREF_display_history(workspace: str, manifest: dict[str, Any], public_key: bytes) -> int:
    """Display committed history as a bounded-memory stream."""
    del public_key  # The workspace was fully verified immediately before this function.
    count = 0
    for segment in manifest["segments"]:
        path = os.path.join(workspace, segment["file"])
        for block in PREF_iter_segment_blocks(path, segment["committed_offset"]):
            PREF_print_operation_summary(block)
            count += 1
    if count == 0:
        PREF_print(PREF_translate("no_operations"))
        return 0
    PREF_print(PREF_translate("operations_found"), count)
    return count


