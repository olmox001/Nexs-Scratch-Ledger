"""
Nexs-Scratch-Ledger - Universal Signed Incremental Ledger

This file is intentionally self-contained and uses one authoritative
implementation. Legacy definitions are not retained.

Security model, briefly:
- Persisted data stays readable JSON; this is integrity/authenticity, not encryption.
- A write key is derived at runtime from username + password + program hash.
- Blank username AND password select the documented generic identity mode.
- The private signing seed is never written to the workspace.
- Ed25519 signs the manifest and every ledger block.
- A public read key identifies the ledger/program context and is persisted.
- An optional external trust-anchor *directory* pins the expected Ed25519 public
  key per logical workspace name. The directory location can be overridden via
  the environment variable NEXS_TRUST_ANCHOR_DIR (must be an absolute path).
  For hardened deployments the anchor directory should live outside the
  program directory (e.g. /etc/nexs/trust_anchors on POSIX,
  %PROGRAMDATA%\\Nexs\\trust_anchors on Windows).
- When NEXS_REQUIRE_EXPLICIT_ANCHOR=1, missing anchor persistence aborts
  workspace creation: TOFU is disabled entirely and enrollment must succeed.
- A program/runtime mismatch allows verified read-only access but disables writes.
- The hash chain remains incremental and append-oriented.
- Crash recovery never silently discards a complete invalid tail.
- Dataset mutations are represented as signed sequential statements.
- Periodic dataset checkpoints re-sign a canonical snapshot.

Append performance contract:
- PREF_append_block is O(1) with respect to the number of already-committed
  operations. Full-chain verification is an *opening-time* operation and is
  performed once by PREF_open_workspace. Re-verifying the full chain on every
  append would turn the commit path into O(n^2). See PREF_append_block for the
  security rationale that justifies the O(1) pre-write checks.

Locking model (advisory, not a security boundary):
- The workspace lock is implemented with POSIX flock / Windows msvcrt.locking,
  which is *advisory*: a hostile or careless process that does not participate
  in the contract may still mutate the files. Integrity of committed data is
  enforced by the signed hash chain and the signed manifest, not by the lock.
  The lock exists only to prevent accidental concurrent well-behaved writers.
- Manifest validation order: cryptographic signature verification is performed
  before full structural validation, so that malformed-but-signed content is
  rejected at the cryptographic layer before schema parsing is attempted.

Required external dependencies:
    cryptography>=41 (Ed25519)
    argon2-cffi>=23 (Argon2id key derivation)

If a dependency is missing, the program fails closed instead of silently
falling back to a weaker authentication primitive.
"""

