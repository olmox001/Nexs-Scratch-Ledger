def PREF_dataset_hash(dataset: Any) -> str:
    """Return the canonical SHA-256 hash of a JSON-compatible dataset."""
    PREF_require_json_value(dataset)
    return PREF_sha256_bytes(PREF_canonical_json(dataset))


def PREF_dataset_deep_copy(dataset: Any) -> Any:
    """Create a deterministic JSON round-trip copy to avoid aliasing mutable state."""
    return json.loads(PREF_canonical_json(dataset).decode("utf-8"))


def PREF_dataset_get_parent(dataset: Any, path: list[str | int]) -> tuple[Any, str | int]:
    """Resolve a bounded JSON path and return its parent plus final component."""
    if not isinstance(path, list) or not path or len(path) > PREF_MAX_DATASET_PATH_COMPONENTS:
        raise ValueError(PREF_translate("err_dataset_path_empty"))
    current = dataset
    for component in path[:-1]:
        if isinstance(current, dict) and isinstance(component, str) and component in current:
            current = current[component]
        elif isinstance(current, list) and type(component) is int and 0 <= component < len(current):
            current = current[component]
        else:
            raise KeyError(PREF_translate_format("err_dataset_parent_missing", component=component))
    return current, path[-1]


def PREF_dataset_apply_statement(dataset: Any, statement: dict[str, Any]) -> Any:
    """Apply one bounded deterministic dataset statement without mutating its input."""
    PREF_require_json_value(dataset)
    PREF_require_json_value(statement)
    if not isinstance(statement, dict):
        raise ValueError(PREF_translate("err_dataset_statement_schema"))
    if set(statement) - {"command", "path", "value"}:
        raise ValueError(PREF_translate("err_dataset_unknown_fields"))
    command = statement.get("command")
    raw_path = statement.get("path")
    if command not in {"set", "delete", "append"} or not isinstance(raw_path, list) or not raw_path:
        raise ValueError(PREF_translate("err_dataset_command"))
    if len(raw_path) > PREF_MAX_DATASET_PATH_COMPONENTS:
        raise ValueError(PREF_translate("err_dataset_path_too_deep"))
    path: list[str | int] = []
    for component in raw_path:
        if isinstance(component, str):
            if len(component) > PREF_MAX_JSON_STRING_CHARS:
                raise ValueError(PREF_translate("err_dataset_component_too_long"))
            path.append(component)
        elif type(component) is int:
            path.append(component)
        else:
            raise ValueError(PREF_translate("err_dataset_component_invalid"))

    result = PREF_dataset_deep_copy(dataset)
    parent, key = PREF_dataset_get_parent(result, path)
    value = statement.get("value")
    if command in {"set", "append"}:
        PREF_require_json_value(value)

    if command == "set":
        if isinstance(parent, dict) and isinstance(key, str):
            parent[key] = PREF_dataset_deep_copy(value)
        elif isinstance(parent, list) and type(key) is int and 0 <= key < len(parent):
            parent[key] = PREF_dataset_deep_copy(value)
        else:
            raise KeyError(PREF_translate("err_dataset_target_not_writable"))
    elif command == "delete":
        if isinstance(parent, dict) and isinstance(key, str):
            if key not in parent:
                raise KeyError(PREF_translate("err_dataset_delete_missing"))
            del parent[key]
        elif isinstance(parent, list) and type(key) is int and 0 <= key < len(parent):
            del parent[key]
        else:
            raise KeyError(PREF_translate("err_dataset_delete_invalid"))
    else:
        if not isinstance(parent, list) or type(key) is not int or key != len(parent):
            raise KeyError(PREF_translate("err_dataset_append_index"))
        parent.append(PREF_dataset_deep_copy(value))

    PREF_require_json_value(result)
    return result


def PREF_create_dataset_genesis(
    workspace: str,
    manifest: dict[str, Any],
    seed: bytes,
    public_key: bytes,
    dataset_id: str,
    dataset: Any,
) -> tuple[Any, dict[str, Any]]:
    """Create one and only one signed genesis record for a dataset id.

    The genesis check uses the committed ledger history directly; it does not
    rely on the replay API (which requires an existing genesis to succeed).
    """
    if not isinstance(dataset_id, str) or not dataset_id.strip() or len(dataset_id) > PREF_MAX_DATASET_ID_CHARS:
        raise ValueError(PREF_translate("err_dataset_id"))
    PREF_require_json_value(dataset)

    operations = PREF_read_all_operations(workspace, manifest)
    for block in operations:
        if block["operation_type"] == "dataset_genesis" and block["payload"].get("dataset_id") == dataset_id:
            raise RuntimeError(PREF_translate("err_dataset_genesis_exists"))

    payload = {
        "dataset_id": dataset_id,
        "revision": 0,
        "dataset_hash": PREF_dataset_hash(dataset),
        "snapshot": PREF_dataset_deep_copy(dataset),
    }
    now = datetime.now(timezone.utc)
    block = PREF_commit_operation(workspace, manifest, seed, public_key, "dataset_genesis", payload, now, now)
    return PREF_dataset_deep_copy(dataset), block


def PREF_commit_dataset_statement(
    workspace: str,
    manifest: dict[str, Any],
    seed: bytes,
    public_key: bytes,
    dataset_id: str,
    revision: int,
    dataset: Any,
    statement: dict[str, Any],
) -> tuple[Any, dict[str, Any]]:
    """Commit a statement only when the caller's dataset revision is the signed latest revision.

    The dataset must already have a signed genesis record; a statement against a
    dataset that does not exist is rejected before any write is attempted.
    """
    if not isinstance(dataset_id, str) or not dataset_id.strip() or len(dataset_id) > PREF_MAX_DATASET_ID_CHARS:
        raise ValueError(PREF_translate("err_dataset_id"))
    if type(revision) is not int or revision < 0:
        raise ValueError(PREF_translate("err_dataset_revision"))

    operations = PREF_read_all_operations(workspace, manifest)
    # If no genesis exists for this dataset, the replay call raises; surface that
    # as a clean error instead of attempting a partial-state heuristic.
    try:
        ledger_state, ledger_revision = PREF_replay_dataset_ledger(operations, dataset_id)
    except RuntimeError as exc:
        raise RuntimeError(PREF_translate_format("err_dataset_no_genesis", dataset_id=dataset_id)) from exc

    if ledger_revision != revision or PREF_dataset_hash(ledger_state) != PREF_dataset_hash(dataset):
        raise RuntimeError(PREF_translate("err_dataset_state_mismatch"))

    next_dataset = PREF_dataset_apply_statement(dataset, statement)
    next_revision = revision + 1
    payload = {
        "dataset_id": dataset_id,
        "revision": next_revision,
        "statement": PREF_dataset_deep_copy(statement),
        "result_hash": PREF_dataset_hash(next_dataset),
    }
    now = datetime.now(timezone.utc)
    block = PREF_commit_operation(workspace, manifest, seed, public_key, "dataset_statement", payload, now, now)
    if next_revision % PREF_DATASET_CHECKPOINT_INTERVAL == 0:
        checkpoint = PREF_commit_dataset_checkpoint(workspace, manifest, seed, public_key, dataset_id, next_revision, next_dataset)
        PREF_print(PREF_translate("dataset_checkpoint"), checkpoint["operation_number"])
    return next_dataset, block


def PREF_commit_dataset_checkpoint(
    workspace: str,
    manifest: dict[str, Any],
    seed: bytes,
    public_key: bytes,
    dataset_id: str,
    revision: int,
    dataset: Any,
) -> dict[str, Any]:
    """Periodically sign a full dataset snapshot and its canonical hash."""
    snapshot = PREF_dataset_deep_copy(dataset)
    raw_snapshot = PREF_canonical_json(snapshot)
    if len(raw_snapshot) > PREF_MAX_DATASET_CHECKPOINT_BYTES:
        raise RuntimeError(PREF_translate("err_dataset_checkpoint_too_large"))
    payload = {
        "dataset_id": dataset_id,
        "revision": revision,
        "dataset_hash": PREF_sha256_bytes(raw_snapshot),
        "snapshot": snapshot,
    }
    now = datetime.now(timezone.utc)
    return PREF_commit_operation(
        workspace,
        manifest,
        seed,
        public_key,
        "dataset_checkpoint",
        payload,
        now,
        now,
    )


def PREF_replay_dataset_ledger(
    operations: list[dict[str, Any]],
    dataset_id: str,
) -> tuple[Any, int]:
    """Rebuild a dataset strictly from the signed operation sequence."""
    state: Any | None = None
    revision = -1
    for block in operations:
        operation_type = block["operation_type"]
        payload = block["payload"]
        if payload.get("dataset_id") != dataset_id:
            continue
        if operation_type == "dataset_genesis":
            if state is not None:
                raise RuntimeError(PREF_translate("err_dataset_multiple_genesis"))
            state = PREF_dataset_deep_copy(payload["snapshot"])
            revision = int(payload["revision"])
            if PREF_dataset_hash(state) != payload["dataset_hash"]:
                raise RuntimeError(PREF_translate("err_dataset_genesis_hash"))
        elif operation_type == "dataset_statement":
            if state is None:
                raise RuntimeError(PREF_translate("err_dataset_genesis_before"))
            state = PREF_dataset_apply_statement(state, payload["statement"])
            expected_revision = revision + 1
            if payload["revision"] != expected_revision:
                raise RuntimeError(PREF_translate("err_dataset_revision_seq"))
            if PREF_dataset_hash(state) != payload["result_hash"]:
                raise RuntimeError(PREF_translate("err_dataset_result_hash"))
            revision = expected_revision
        elif operation_type == "dataset_checkpoint":
            snapshot = PREF_dataset_deep_copy(payload["snapshot"])
            if PREF_dataset_hash(snapshot) != payload["dataset_hash"]:
                raise RuntimeError(PREF_translate("err_dataset_checkpoint_hash"))
            if payload["revision"] != revision:
                raise RuntimeError(PREF_translate("err_dataset_checkpoint_revision"))
            state = snapshot
    if state is None:
        raise RuntimeError(PREF_translate("err_dataset_no_genesis_replay"))
    return state, revision


