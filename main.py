def PREF_normalize_workspace_name(name: str) -> str:
    """Normalize a logical workspace name without using it directly as a path."""
    return unicodedata.normalize("NFC", name.strip())


def PREF_validate_workspace_name(name: str) -> bool:
    """Reject empty, ambiguous, oversized, control-containing, or path-like names."""
    if not isinstance(name, str):
        return False
    normalized = PREF_normalize_workspace_name(name)
    if not normalized or normalized in (".", "..") or len(normalized) > PREF_MAX_WORKSPACE_NAME_CHARS:
        return False
    for character in normalized:
        codepoint = ord(character)
        if codepoint < 32 or codepoint == 127 or character in ("/", "\\", "\x00"):
            return False
    return True


def PREF_physical_workspace_name(logical_name: str) -> str:
    """Map an untrusted logical name to a deterministic safe filesystem name."""
    digest = PREF_sha256_text(PREF_normalize_workspace_name(logical_name))
    return f"nxsl_{digest[:48]}.{PREF_FILE_EXTENSION}"


def PREF_workspace_path(logical_name: str, directory: str = ".") -> str:
    """Build the physical workspace path from the safe digest-based name."""
    if not PREF_validate_workspace_name(logical_name):
        raise ValueError(PREF_translate("err_workspace_name_invalid"))
    return os.path.join(directory, PREF_physical_workspace_name(logical_name))


def PREF_manifest_path(workspace: str) -> str:
    return os.path.join(workspace, PREF_MANIFEST_NAME)


def PREF_segments_path(workspace: str) -> str:
    return os.path.join(workspace, PREF_SEGMENT_DIRECTORY)


def PREF_staging_path(workspace: str) -> str:
    return os.path.join(workspace, PREF_STAGING_DIRECTORY)


def PREF_segment_path(workspace: str, number: int) -> str:
    if number < 1:
        raise ValueError(PREF_translate("err_segment_path_invalid"))
    return os.path.join(PREF_segments_path(workspace), f"{number:012d}.nxsb")


def PREF_is_regular_file(path: str) -> bool:
    """Require a non-symlink regular file."""
    try:
        return os.path.isfile(path) and not os.path.islink(path)
    except OSError:
        return False


def PREF_safe_workspace_directory(workspace: str) -> None:
    """Verify workspace directories and critical children are real filesystem objects."""
    if os.path.islink(workspace) or not os.path.isdir(workspace):
        raise RuntimeError(PREF_translate("err_workspace_dir_missing"))
    if not PREF_is_regular_file(PREF_manifest_path(workspace)):
        raise RuntimeError(PREF_translate("err_workspace_manifest_missing"))
    segments = PREF_segments_path(workspace)
    staging = PREF_staging_path(workspace)
    if os.path.islink(segments) or not os.path.isdir(segments):
        raise RuntimeError(PREF_translate("err_workspace_segments_missing"))
    if os.path.islink(staging) or not os.path.isdir(staging):
        raise RuntimeError(PREF_translate("err_workspace_staging_missing"))
    lock_path = os.path.join(workspace, PREF_LOCK_NAME)
    if os.path.lexists(lock_path) and os.path.islink(lock_path):
        raise RuntimeError(PREF_translate("err_workspace_lock_symlink"))


@contextlib.contextmanager
def PREF_exclusive_workspace_lock(workspace: str) -> Iterator[None]:
    """Acquire an *advisory* exclusive lock without following a lock-file symlink.

    This lock is advisory only (POSIX flock / Windows msvcrt.locking). A hostile
    or careless process that does not participate in the contract may still
    mutate the workspace files. Committed-data integrity is enforced by the
    signed hash chain and the signed manifest, not by this lock. The lock exists
    solely to prevent accidental concurrent *cooperating* writers.
    """
    PREF_safe_workspace_directory(workspace)
    lock_path = os.path.join(workspace, PREF_LOCK_NAME)
    flags = os.O_RDWR | os.O_CREAT
    nofollow = getattr(os, "O_NOFOLLOW", 0)
    flags |= nofollow
    try:
        descriptor = os.open(lock_path, flags, 0o600)
    except OSError as exc:
        raise RuntimeError(PREF_translate("err_workspace_lock_open")) from exc

    lock_file = os.fdopen(descriptor, "a+b", closefd=True)
    try:
        if os.name == "nt":
            import msvcrt
            lock_file.seek(0)
            if os.path.getsize(lock_path) == 0:
                lock_file.write(b"0")
                lock_file.flush()
            lock_file.seek(0)
            try:
                msvcrt.locking(lock_file.fileno(), msvcrt.LK_NBLCK, 1)
            except OSError as exc:
                raise RuntimeError(PREF_translate("err_workspace_already_open")) from exc
        else:
            import fcntl
            try:
                fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError as exc:
                raise RuntimeError(PREF_translate("err_workspace_already_open")) from exc
        yield
    finally:
        try:
            if os.name == "nt":
                import msvcrt
                lock_file.seek(0)
                msvcrt.locking(lock_file.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                import fcntl
                fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)
        except OSError:
            pass
        lock_file.close()


