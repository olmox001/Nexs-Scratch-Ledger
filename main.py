def PREF_compute_runtime_identity() -> dict[str, Any]:
    """Fingerprint the running program and every explicitly trusted extension."""
    program_path = os.path.realpath(os.path.abspath(__file__))
    base_directory = os.path.dirname(program_path)
    program_hash = PREF_hash_file_streaming(program_path)
    extension_directory = os.path.join(base_directory, PREF_EXTENSION_DIRECTORY_NAME)
    extensions: list[dict[str, str]] = []

    if os.path.isdir(extension_directory):
        for entry in sorted(os.scandir(extension_directory), key=lambda item: item.name):
            if entry.name == "__pycache__":
                continue
            if entry.is_symlink():
                raise RuntimeError(PREF_translate_format("err_runtime_symlink_ext", name=entry.name))
            if not entry.is_file() or not entry.name.endswith(".py"):
                continue
            module_name = os.path.splitext(entry.name)[0]
            if not module_name.isidentifier() or keyword.iskeyword(module_name):
                raise RuntimeError(PREF_translate_format("err_runtime_invalid_module", name=entry.name))
            extension_hash = PREF_hash_file_streaming(entry.path)
            expected = PREF_TRUSTED_EXTENSION_HASHES.get(entry.name)
            if expected is None or not PREF_secure_compare(expected.lower(), extension_hash.lower()):
                raise RuntimeError(PREF_translate_format("err_runtime_untrusted_ext", name=entry.name))
            extensions.append(
                {
                    "file": os.path.relpath(entry.path, base_directory),
                    "sha256": extension_hash,
                }
            )

    base_identity = {
        "schema_version": PREF_SCHEMA_VERSION,
        "program_version": PREF_PROGRAM_VERSION,
        "program_hash": program_hash,
        "extensions": extensions,
        "python_implementation": sys.implementation.name,
        "python_version": platform.python_version(),
    }
    runtime_fingerprint = PREF_sha256_bytes(PREF_canonical_json(base_identity))
    base_identity["runtime_fingerprint"] = runtime_fingerprint
    base_identity["program_version_hash"] = f"{PREF_PROGRAM_VERSION}+{runtime_fingerprint[:16]}"
    base_identity["program_path"] = os.path.relpath(program_path, base_directory)
    return base_identity


def PREF_verify_runtime_identity_unchanged(identity: dict[str, Any]) -> None:
    """Recompute the executable identity immediately before writes and fail closed on any change."""
    if not isinstance(identity, dict):
        raise RuntimeError(PREF_translate("err_runtime_invalid_identity"))
    current = PREF_compute_runtime_identity()
    if not PREF_hashes_equal(current.get("program_hash"), identity.get("program_hash")):
        raise RuntimeError(PREF_translate("err_runtime_program_changed"))
    if not PREF_hashes_equal(current.get("runtime_fingerprint"), identity.get("runtime_fingerprint")):
        raise RuntimeError(PREF_translate("err_runtime_identity_changed"))


def PREF_load_trusted_python_extensions(identity: dict[str, Any]) -> None:
    """Load only hash-allow-listed Python extensions with a strict registry contract.

    Isolation contract: extensions execute in the same interpreter as the
    program. Hash verification is the only gate; once a module has been
    verified, it runs with full process privileges. Do not add a module to
    PREF_TRUSTED_EXTENSION_HASHES unless its code has been audited.
    """
    global PREF_LOADED_EXTENSIONS
    base_directory = os.path.dirname(os.path.realpath(os.path.abspath(__file__)))
    PREF_LOADED_EXTENSIONS = {}
    registered_names: set[str] = set()

    for extension in identity["extensions"]:
        path = os.path.join(base_directory, extension["file"])
        if os.path.islink(path) or not os.path.isfile(path):
            raise RuntimeError(PREF_translate_format("err_runtime_unsafe_ext_path", file=extension["file"]))
        expected_hash = extension["sha256"]
        actual_hash = PREF_hash_file_streaming(path)
        if not PREF_secure_compare(expected_hash.lower(), actual_hash.lower()):
            raise RuntimeError(PREF_translate_format("err_runtime_ext_changed", file=extension["file"]))

        module_name = os.path.splitext(os.path.basename(path))[0]
        specification = importlib.util.spec_from_file_location(f"nexs_trusted_{module_name}", path)
        if specification is None or specification.loader is None:
            raise RuntimeError(PREF_translate_format("err_runtime_ext_prepare", module=module_name))
        module = importlib.util.module_from_spec(specification)
        try:
            specification.loader.exec_module(module)
        except Exception as exc:
            raise RuntimeError(PREF_translate_format("err_runtime_ext_import", module=module_name)) from exc
        registry = getattr(module, "PREF_FUNCTIONS", {})
        if not isinstance(registry, dict) or len(registry) > 1024:
            raise RuntimeError(PREF_translate_format("err_runtime_ext_registry", module=module_name))
        for function_name, function in registry.items():
            if (
                not isinstance(function_name, str)
                or not function_name.startswith("PREF_")
                or not function_name.isidentifier()
                or not callable(function)
            ):
                raise RuntimeError(PREF_translate_format("err_runtime_ext_function", module=module_name))
            if function_name in registered_names:
                raise RuntimeError(PREF_translate_format("err_runtime_ext_duplicate", name=function_name))
            registered_names.add(function_name)
            PREF_LOADED_EXTENSIONS[function_name] = function


def PREF_derive_private_seed(username: str, password: str, program_hash: str) -> bytes:
    """Derive the 32-byte Ed25519 seed; the derived secret never leaves memory.

    Pipeline:
      1. Normalize the username and validate all length bounds.
      2. Compute a fixed-length identity digest over the domain-separated tuple
         (domain || username || 0x00 || password || 0x00 || program_hash).
         The plaintext password never reaches the KDF; only its SHA-256 digest
         does.
      3. Feed that digest to Argon2id with a salt derived from the program hash.

    The program hash is bound into the identity digest itself (not only into
    the salt), so the same credentials on two different program versions yield
    two unrelated seeds. This is intentional and part of the security model.
    """
    if not isinstance(username, str) or not isinstance(password, str):
        raise TypeError(PREF_translate("err_credentials_types"))
    if not isinstance(program_hash, str) or len(program_hash) != 64:
        raise ValueError(PREF_translate("err_manifest_program_hash"))
    try:
        bytes.fromhex(program_hash)
    except ValueError as exc:
        raise ValueError(PREF_translate("err_manifest_program_hash")) from exc
    normalized_username = PREF_normalize_username(username)
    if len(normalized_username) > PREF_MAX_USERNAME_CHARS:
        raise ValueError(PREF_translate("err_credentials_user_empty"))
    if len(password) > PREF_MAX_PASSWORD_CHARS:
        raise ValueError(PREF_translate("err_credentials_user_empty"))

    program_bytes = program_hash.encode("ascii")
    if not normalized_username and not password:
        base_material = hashlib.sha256(b"NEXS-GENERIC-WRITE|0|" + program_bytes).digest()
    elif normalized_username and password:
        raw_material = (
            b"NEXS-USER-WRITE|"
            + normalized_username.encode("utf-8")
            + b"\x00"
            + password.encode("utf-8")
            + b"\x00"
            + program_bytes
        )
        base_material = hashlib.sha256(raw_material).digest()
    else:
        raise ValueError(PREF_translate("err_credentials_user_empty"))

    salt = hashlib.sha256(b"NEXS-ARGON2-SALT|" + program_bytes).digest()
    try:
        return hash_secret_raw(
            secret=base_material,
            salt=salt,
            time_cost=PREF_ARGON2_TIME_COST,
            memory_cost=PREF_ARGON2_MEMORY_COST_KIB,
            parallelism=PREF_ARGON2_PARALLELISM,
            hash_len=PREF_ARGON2_HASH_LEN,
            type=Argon2Type.ID,
        )
    except Exception as exc:
        raise RuntimeError(PREF_translate("err_argon2_failed")) from exc


def PREF_public_key_from_seed(seed: bytes) -> bytes:
    """Return the raw Ed25519 public key corresponding to a private seed."""
    if len(seed) != 32:
        raise ValueError(PREF_translate("err_seed_invalid"))
    private_key = Ed25519PrivateKey.from_private_bytes(seed)
    return private_key.public_key().public_bytes(
        serialization.Encoding.Raw,
        serialization.PublicFormat.Raw,
    )


def PREF_base64_encode(data: bytes) -> str:
    """Encode bytes as compact ASCII base64."""
    return base64.b64encode(data).decode("ascii")


def PREF_base64_decode(text: str, expected_length: int) -> bytes:
    """Decode strict base64 and enforce the expected byte length."""
    if not isinstance(text, str):
        raise ValueError(PREF_translate("err_base64_text"))
    try:
        decoded = base64.b64decode(text.encode("ascii"), validate=True)
    except (ValueError, UnicodeEncodeError) as exc:
        raise ValueError(PREF_translate("err_base64_invalid")) from exc
    if len(decoded) != expected_length:
        raise ValueError(PREF_translate("err_base64_length"))
    return decoded


def PREF_make_public_read_key(
    program_hash: str,
    runtime_fingerprint: str,
    ledger_id: str,
) -> str:
    """Create the public ledger identity key used for non-secret read validation."""
    material = (
        f"NEXS-READ-V{PREF_SCHEMA_VERSION}|{program_hash}|{runtime_fingerprint}|{ledger_id}"
    ).encode("ascii")
    return PREF_sha256_bytes(material)


def PREF_sign_bytes(seed: bytes, data: bytes) -> str:
    """Sign bytes with the runtime-only private seed."""
    return PREF_base64_encode(Ed25519PrivateKey.from_private_bytes(seed).sign(data))


def PREF_verify_signature(public_key: bytes, data: bytes, signature_b64: str) -> bool:
    """Verify an Ed25519 signature and return False on signature-format failure."""
    try:
        from cryptography.exceptions import InvalidSignature

        signature = PREF_base64_decode(signature_b64, 64)
        Ed25519PublicKey.from_public_bytes(public_key).verify(signature, data)
        return True
    except (InvalidSignature, ValueError, TypeError):
        return False


def PREF_hashes_equal(left: Any, right: Any) -> bool:
    """Compare hash values exactly, including the valid case where both values are empty strings."""
    if not isinstance(left, str) or not isinstance(right, str):
        return False
    return hmac.compare_digest(left, right)


def PREF_explicit_anchor_required() -> bool:
    """Return True when NEXS_REQUIRE_ANCHOR forces anchor enrollment."""
    value = os.environ.get(PREF_REQUIRE_EXPLICIT_ANCHOR_ENV_VAR, "").strip()
    return value in {"1", "true", "yes", "on"}


