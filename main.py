def PREF_allowed_external_path(path: str) -> str:
    """Restrict external data resources to the existing ./external directory and reject symlinks."""
    base_directory = os.path.dirname(os.path.realpath(os.path.abspath(__file__)))
    external_directory = os.path.join(base_directory, PREF_EXTERNAL_DIRECTORY_NAME)
    if os.path.islink(external_directory) or not os.path.isdir(external_directory):
        raise RuntimeError(PREF_translate("err_resource_dir_missing"))
    if not isinstance(path, str) or not path:
        raise RuntimeError(PREF_translate("err_resource_path_invalid"))
    if os.path.islink(path):
        raise RuntimeError(PREF_translate("err_resource_symlink"))
    absolute = os.path.realpath(os.path.abspath(path))
    if not os.path.isfile(absolute):
        raise RuntimeError(PREF_translate("err_resource_not_file"))
    try:
        if os.path.commonpath([os.path.realpath(external_directory), absolute]) != os.path.realpath(external_directory):
            raise RuntimeError(PREF_translate("err_resource_outside_dir"))
    except ValueError as exc:
        raise RuntimeError(PREF_translate("err_resource_path_invalid")) from exc
    return absolute


def PREF_describe_external_resource(path: str) -> dict[str, Any]:
    """Hash and size an external data file for later inclusion in a signed operation."""
    absolute = PREF_allowed_external_path(path)
    size = os.path.getsize(absolute)
    if size > PREF_MAX_RESOURCE_BYTES:
        raise RuntimeError(PREF_translate("err_resource_too_large"))
    base_directory = os.path.dirname(os.path.realpath(os.path.abspath(__file__)))
    descriptor = {
        "path": os.path.relpath(absolute, base_directory),
        "sha256": PREF_hash_file_streaming(absolute),
        "size": size,
    }
    PREF_EXTERNAL_RESOURCES[descriptor["path"]] = descriptor
    return descriptor


def PREF_read_stable_file_bytes(path: str, max_bytes: int) -> tuple[bytes, str]:
    """Read and hash one regular file through a stable descriptor."""
    if max_bytes < 0:
        raise ValueError(PREF_translate("err_resource_max_negative"))
    if os.path.islink(path) or not os.path.isfile(path):
        raise RuntimeError(PREF_translate_format("err_resource_not_file_path", path=path))
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(path, flags)
    except OSError as exc:
        raise RuntimeError(PREF_translate_format("err_resource_open", path=path)) from exc
    try:
        initial = os.fstat(descriptor)
        if not stat.S_ISREG(initial.st_mode):
            raise RuntimeError(PREF_translate_format("err_resource_not_regular", path=path))
        if initial.st_size > max_bytes:
            raise RuntimeError(PREF_translate_format("err_resource_too_large_path", path=path))
        hasher = hashlib.sha256()
        chunks: list[bytes] = []
        total = 0
        with os.fdopen(descriptor, "rb", closefd=True) as source:
            for _chunk_index in range((max_bytes // PREF_HASH_CHUNK_BYTES) + 1):
                chunk = source.read(PREF_HASH_CHUNK_BYTES)
                if not chunk:
                    break
                total += len(chunk)
                if total > max_bytes:
                    raise RuntimeError(PREF_translate_format("err_resource_too_large_path", path=path))
                chunks.append(chunk)
                hasher.update(chunk)
            else:
                raise RuntimeError(PREF_translate_format("err_resource_read_bound", path=path))
        descriptor = -1
        final = os.stat(path, follow_symlinks=False)
        if (
            not stat.S_ISREG(final.st_mode)
            or getattr(final, "st_dev", 0) != getattr(initial, "st_dev", 0)
            or final.st_size != initial.st_size
            or final.st_mtime_ns != getattr(initial, "st_mtime_ns", final.st_mtime_ns)
            or getattr(final, "st_ino", 0) != getattr(initial, "st_ino", 0)
        ):
            raise RuntimeError(PREF_translate_format("err_resource_changed", path=path))
        data = b"".join(chunks)
        return data, hasher.hexdigest()
    except OSError as exc:
        raise RuntimeError(PREF_translate_format("err_resource_read_failed", path=path)) from exc
    finally:
        if descriptor != -1:
            try:
                os.close(descriptor)
            except OSError:
                pass


def PREF_load_verified_json(path: str) -> tuple[Any, dict[str, Any]]:
    """Load external JSON as data only and return its immutable descriptor."""
    absolute = PREF_allowed_external_path(path)
    raw, stable_hash = PREF_read_stable_file_bytes(absolute, PREF_MAX_RESOURCE_BYTES)
    descriptor = {
        "path": os.path.relpath(absolute, os.path.dirname(os.path.realpath(os.path.abspath(__file__)))),
        "sha256": stable_hash,
        "size": len(raw),
    }
    PREF_EXTERNAL_RESOURCES[descriptor["path"]] = descriptor
    try:
        value = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RuntimeError(PREF_translate("err_resource_json_invalid")) from exc
    PREF_require_json_value(value)
    PREF_print(PREF_translate("resource_json_loaded"), descriptor["path"])
    return value, descriptor


def PREF_open_readonly_sqlite(path: str) -> tuple[sqlite3.Connection, dict[str, Any]]:
    """Open an external SQLite file strictly read-only and query-only.

    Uses pathlib.Path.as_uri() to obtain a portable file:// URI (handles Windows
    drive letters and POSIX absolute paths uniformly), then appends ?mode=ro so
    the connection is enforced read-only by SQLite itself.
    """
    absolute = PREF_allowed_external_path(path)
    descriptor = PREF_describe_external_resource(absolute)
    try:
        base_uri = Path(absolute).as_uri()
    except ValueError as exc:
        raise RuntimeError(PREF_translate("err_sqlite_uri")) from exc
    uri = base_uri + "?mode=ro"
    connection: sqlite3.Connection | None = None
    try:
        connection = sqlite3.connect(uri, uri=True, isolation_level=None)
        connection.execute("PRAGMA query_only=ON")
        connection.execute("PRAGMA foreign_keys=ON")
    except sqlite3.Error as exc:
        if connection is not None:
            try:
                connection.close()
            except sqlite3.Error:
                pass
        raise RuntimeError(PREF_translate("err_sqlite_open")) from exc
    PREF_print(PREF_translate("resource_sqlite_loaded"), descriptor["path"])
    return connection, descriptor


def PREF_attach_external_resources(payload: dict[str, Any]) -> dict[str, Any]:
    """Attach a bounded, deterministic list of content-addressed external resources.

    The registry of pending external resources is consumed by this call: after
    the descriptors have been attached to the payload, the registry is cleared
    so that a later payload cannot accidentally carry stale resource
    descriptors that were registered for an earlier operation.
    """
    global PREF_EXTERNAL_RESOURCES
    PREF_require_json_value(payload)
    if len(PREF_EXTERNAL_RESOURCES) > PREF_MAX_EXTERNAL_RESOURCES_PER_PAYLOAD:
        raise RuntimeError(PREF_translate("err_resource_too_many"))
    result = PREF_dataset_deep_copy(payload)
    descriptors = [
        dict(PREF_EXTERNAL_RESOURCES[key])
        for key in sorted(PREF_EXTERNAL_RESOURCES)
    ]
    result["external_resources"] = descriptors
    PREF_require_json_value(result)
    # Consume the registry: descriptors are now bound to this payload only.
    PREF_EXTERNAL_RESOURCES = {}
    return result


