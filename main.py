def PREF_self_test_check(condition: bool, label: str) -> None:
    """Count and enforce one self-test invariant without relying on Python assert semantics."""
    global PREF_SELF_TEST_CHECKS
    PREF_SELF_TEST_CHECKS += 1
    if not condition:
        raise AssertionError(f"SELF-TEST CHECK {PREF_SELF_TEST_CHECKS} FAILED: {label}")


def PREF_self_test_expect_failure(function: Callable[..., Any], label: str, *args: Any, **kwargs: Any) -> None:
    """Require a callable to fail closed with an exception."""
    try:
        function(*args, **kwargs)
    except Exception:
        PREF_self_test_check(True, label)
        return
    PREF_self_test_check(False, label)


def PREF_self_test_crypto(identity: dict[str, Any]) -> None:
    """Test key derivation, signatures, exact hash equality, and credential modes."""
    generic_seed = PREF_derive_private_seed("", "", identity["program_hash"])
    PREF_self_test_check(len(generic_seed) == 32, "generic seed length")
    generic_public = PREF_public_key_from_seed(generic_seed)
    PREF_self_test_check(len(generic_public) == 32, "generic public key length")
    payload = b"self-test"
    signature = PREF_sign_bytes(generic_seed, payload)
    PREF_self_test_check(PREF_verify_signature(generic_public, payload, signature), "valid signature")
    PREF_self_test_check(not PREF_verify_signature(generic_public, b"changed", signature), "tampered signature")
    PREF_self_test_check(PREF_hashes_equal("", ""), "empty hashes compare equal")
    PREF_self_test_check(not PREF_hashes_equal("", "0"), "empty hash differs from non-empty")
    PREF_self_test_check(PREF_hashes_equal(identity["program_hash"], identity["program_hash"]), "identical program hashes compare equal")
    PREF_self_test_check(not PREF_hashes_equal(identity["program_hash"], identity["runtime_fingerprint"]), "different hashes do not compare equal")

    user_seed_a = PREF_derive_private_seed("Alice", "Correct Horse", identity["program_hash"])
    user_seed_b = PREF_derive_private_seed("Alice", "Wrong Password", identity["program_hash"])
    PREF_self_test_check(user_seed_a != user_seed_b, "password changes derived seed")
    PREF_self_test_check(PREF_public_key_from_seed(user_seed_a) != PREF_public_key_from_seed(user_seed_b), "password changes public key")
    user_seed_case = PREF_derive_private_seed(" alice ", "Correct Horse", identity["program_hash"])
    PREF_self_test_check(user_seed_case == user_seed_a, "username NFC/trim/casefold normalization")
    PREF_self_test_expect_failure(PREF_derive_private_seed, "partial credential derivation rejected", "Alice", "", identity["program_hash"])
    PREF_self_test_expect_failure(PREF_derive_private_seed, "invalid program hash rejected", "", "", "not-a-hash")
    PREF_self_test_expect_failure(PREF_public_key_from_seed, "invalid seed length rejected", b"x")
    PREF_self_test_expect_failure(PREF_base64_decode, "invalid base64 rejected", "!!!!", 32)
    PREF_self_test_check(len(PREF_base64_encode(generic_public)) > 0, "base64 encoding produces data")
    PREF_self_test_check(PREF_base64_decode(PREF_base64_encode(generic_public), 32) == generic_public, "base64 round trip")
    PREF_self_test_check(PREF_secure_compare("abc", "abc"), "secure_compare equal ASCII strings")
    PREF_self_test_check(not PREF_secure_compare("abc", "abd"), "secure_compare unequal ASCII strings")
    PREF_self_test_check(not PREF_secure_compare("abc", "àbc"), "secure_compare rejects non-ASCII")
    PREF_self_test_check(PREF_secure_compare_bytes(b"\x00\x01", b"\x00\x01"), "secure_compare_bytes equal")
    PREF_self_test_check(not PREF_secure_compare_bytes(b"\x00\x01", b"\x00\x02"), "secure_compare_bytes unequal")
    PREF_self_test_check(not PREF_secure_compare_bytes(b"", b"\x00"), "secure_compare_bytes length mismatch")

    # Argon2id determinism and program-hash binding.
    seed_a1 = PREF_derive_private_seed("Alice", "Correct Horse", identity["program_hash"])
    seed_a2 = PREF_derive_private_seed("Alice", "Correct Horse", identity["program_hash"])
    PREF_self_test_check(seed_a1 == seed_a2, "Argon2id derivation is deterministic")
    seed_other_program = PREF_derive_private_seed("Alice", "Correct Horse", "0" * 64)
    PREF_self_test_check(seed_a1 != seed_other_program, "program hash changes derived seed")

    # Credential descriptor contract: fingerprint must match username.
    valid_user_creds = {
        "username": "Alice", "password": "Correct Horse",
        "generic": False, "username_fingerprint": PREF_sha256_text(PREF_normalize_username("Alice")),
    }
    PREF_validate_credentials(valid_user_creds)
    PREF_self_test_check(True, "valid user credentials accepted")
    mismatched = dict(valid_user_creds)
    mismatched["username_fingerprint"] = PREF_sha256_text("other")
    PREF_self_test_expect_failure(PREF_validate_credentials, "fingerprint/username mismatch rejected", mismatched)
    PREF_self_test_expect_failure(
        PREF_validate_credentials,
        "non-hex fingerprint rejected",
        {**valid_user_creds, "username_fingerprint": "z" * 64},
    )
    PREF_validate_credentials({"username": "", "password": "", "generic": True, "username_fingerprint": "0"})
    PREF_self_test_check(True, "generic credentials accepted")
    PREF_self_test_expect_failure(
        PREF_validate_credentials,
        "generic credentials with non-empty username rejected",
        {"username": "x", "password": "", "generic": True, "username_fingerprint": "0"},
    )


