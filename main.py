def PREF_recover_orphan_segment(workspace: str, manifest: dict[str, Any], public_key: bytes, signing_seed: bytes) -> str:
    """Recover only the single immediate next segment; never trust arbitrary extra files."""
    directory = PREF_segments_path(workspace)
    try:
        entries = list(os.scandir(directory))
    except OSError as exc:
        raise RuntimeError(PREF_translate("err_recover_orphan_dir")) from exc

    actual_files: list[str] = []
    for entry in entries:
        if not entry.name.endswith(".nxsb"):
            continue
        if entry.is_symlink() or not entry.is_file(follow_symlinks=False):
            raise RuntimeError(PREF_translate("err_recover_orphan_unsafe"))
        actual_files.append(entry.name)
    actual_files.sort()

    expected_files = [os.path.basename(segment["file"]) for segment in manifest["segments"]]
    extras = [name for name in actual_files if name not in expected_files]
    if not extras:
        return "none"
    if len(extras) != 1:
        raise RuntimeError(PREF_translate("err_recover_orphan_unexpected"))

    expected_next = manifest["current_segment"] + 1
    expected_name = f"{expected_next:012d}.nxsb"
    if extras[0] != expected_name:
        raise RuntimeError(PREF_translate("err_recover_orphan_not_next"))

    orphan_path = os.path.join(directory, expected_name)
    previous_hash = manifest["last_chain_hash"]
    expected_number = manifest["next_operation_number"]
    adopted_count = 0
    final_hash = previous_hash
    truncate_to: int | None = None
    try:
        with open(orphan_path, "rb") as source:
            cursor = 0
            for _frame_index in range(PREF_MAX_ROWS_PER_SEGMENT + 1):
                frame_start = cursor
                raw_line = source.readline(PREF_MAX_BLOCK_BYTES + 1)
                if not raw_line:
                    break
                cursor += len(raw_line)
                if len(raw_line) > PREF_MAX_BLOCK_BYTES:
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                if not raw_line.endswith(b"\n"):
                    truncate_to = frame_start
                    break
                try:
                    block = json.loads(raw_line[:-1].decode("utf-8"))
                except (UnicodeDecodeError, json.JSONDecodeError) as exc:
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid")) from exc
                if not isinstance(block, dict) or block.get("operation_number") != expected_number:
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                if not PREF_verify_block(
                    block,
                    previous_hash,
                    public_key,
                    manifest["program_hash"],
                    manifest["runtime_fingerprint"],
                ):
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                adopted_count += 1
                if adopted_count > PREF_MAX_ROWS_PER_SEGMENT:
                    raise RuntimeError(PREF_translate("err_recover_tail_invalid"))
                previous_hash = block["chain_hash"]
                final_hash = previous_hash
                expected_number += 1
    except OSError as exc:
        raise RuntimeError(PREF_translate("err_recover_orphan_inspect")) from exc

    if truncate_to is not None:
        try:
            with open(orphan_path, "rb+") as target:
                target.truncate(truncate_to)
                target.flush()
                os.fsync(target.fileno())
        except OSError as exc:
            raise RuntimeError(PREF_translate("err_recover_orphan_truncate")) from exc

    if adopted_count == 0:
        try:
            os.remove(orphan_path)
        except OSError as exc:
            raise RuntimeError(PREF_translate("err_recover_orphan_remove")) from exc
        return "removed"

    size = os.path.getsize(orphan_path)
    segment = {
        "segment_number": expected_next,
        "file": f"{PREF_SEGMENT_DIRECTORY}/{expected_name}",
        "rows": adopted_count,
        "committed_offset": size,
        "sealed": adopted_count == PREF_MAX_ROWS_PER_SEGMENT,
        "sha256": PREF_hash_file_streaming(orphan_path) if adopted_count == PREF_MAX_ROWS_PER_SEGMENT else None,
    }
    manifest["segments"].append(segment)
    manifest["current_segment"] = expected_next
    manifest["operation_count"] += adopted_count
    manifest["next_operation_number"] += adopted_count
    manifest["last_chain_hash"] = final_hash
    signed_manifest = PREF_sign_manifest(manifest, signing_seed)
    PREF_write_atomic(PREF_manifest_path(workspace), PREF_canonical_json(signed_manifest) + b"\n")
    manifest.clear()
    manifest.update(signed_manifest)
    return "adopted_truncated" if truncate_to is not None else "adopted"


def PREF_open_workspace(
    workspace: str,
    logical_name: str,
    credentials: dict[str, Any],
    identity: dict[str, Any],
    *,
    perform_recovery: bool = True,
    announce: bool = True,
) -> tuple[dict[str, Any], bytes, bool, bytes | None]:
    """Open, verify, and optionally recover a workspace; recovery is never performed in RO mode."""
    manifest, public_key = PREF_load_manifest(workspace, logical_name)

    if announce:
        anchor_status = PREF_enforce_trust_anchor(logical_name, public_key)
        if anchor_status == "pinned_ok":
            PREF_print(PREF_translate("trust_anchor_ok"))
        else:
            PREF_print(PREF_translate("trust_anchor_missing"))

    write_allowed, seed, reason = PREF_authorize_workspace_write(
        manifest,
        identity,
        credentials,
        public_key,
    )

    if write_allowed and seed is not None:
        if announce:
            PREF_print(PREF_translate("public_key_ok"), manifest["public_read_key"])
            PREF_print(PREF_translate("manifest_identity_ok"))
            PREF_print(PREF_translate("write_authorized"))
        if perform_recovery:
            orphan_status = PREF_recover_orphan_segment(workspace, manifest, public_key, seed)
            if announce:
                if orphan_status in {"adopted", "adopted_truncated"}:
                    PREF_print(PREF_translate("tail_recovered"))
                elif orphan_status == "removed":
                    PREF_print(PREF_translate("tail_removed"))

            recovery_status = PREF_recover_uncommitted_tail(workspace, manifest, public_key, seed)
            if announce:
                if recovery_status in {"adopted", "adopted_truncated"}:
                    PREF_print(PREF_translate("tail_recovered"))
                elif recovery_status == "truncated":
                    PREF_print(PREF_translate("tail_removed"))
    else:
        if announce:
            PREF_print(PREF_translate("public_key_ok"), manifest["public_read_key"])
            if reason in {"version_mismatch", "runtime_changed"}:
                PREF_print(PREF_translate("manifest_program_mismatch"))
                PREF_print(PREF_translate("write_denied_version"))
            elif reason == "credentials_required":
                PREF_print(PREF_translate("write_denied_credentials"))
            elif reason == "credentials_invalid":
                PREF_print(PREF_translate("write_denied_invalid_credentials"))
            elif reason == "credential_mode_mismatch":
                PREF_print(PREF_translate("write_denied_credentials"))
            PREF_print(PREF_translate("read_only_mode"))

        for segment in manifest["segments"]:
            path = os.path.join(workspace, *segment["file"].split("/"))
            if os.path.getsize(path) > segment["committed_offset"]:
                if announce:
                    PREF_print(PREF_translate("tail_present_read_only"))
                break

    verified = PREF_verify_full_chain(workspace, manifest, public_key)
    if announce:
        PREF_print(PREF_translate("chain_ok"), verified)
    return manifest, public_key, write_allowed, seed


def PREF_append_block(
    workspace: str,
    manifest: dict[str, Any],
    seed: bytes,
    block: dict[str, Any],
    public_key: bytes,
) -> None:
    """Verify the live ledger, append exactly one frame, then commit its signed manifest.

    Performance contract: this function is O(1) with respect to the number of
    already-committed operations. Full-chain verification is an *opening-time*
    operation and is performed once by PREF_open_workspace. Re-verifying the
    full chain on every append would turn the commit path into O(n^2) and is
    unnecessary because:

      - we hold the advisory workspace lock;
      - the on-disk manifest is re-read and its Ed25519 signature re-verified
        by PREF_load_manifest before any write;
      - the new block's previous_chain_hash is checked against the signed
        manifest last_chain_hash, so the new block can only extend the exact
        chain we already verified at open time;
      - the next time the workspace is opened, PREF_open_workspace runs the
        full chain verification again and will detect any post-hoc tampering.
    """
    if not isinstance(seed, bytes) or len(seed) != 32:
        raise ValueError(PREF_translate("err_append_seed"))
    if not isinstance(public_key, bytes) or len(public_key) != 32:
        raise ValueError(PREF_translate("err_append_pubkey"))
    if PREF_RUNTIME_IDENTITY is not None:
        PREF_verify_runtime_identity_unchanged(PREF_RUNTIME_IDENTITY)
    if not PREF_secure_compare_bytes(PREF_public_key_from_seed(seed), public_key):
        raise RuntimeError(PREF_translate("err_append_seed_mismatch"))

    # Re-read and re-authenticate the manifest. This detects any external
    # modification of the manifest file since the last append.
    disk_manifest, disk_public_key = PREF_load_manifest(workspace, manifest["logical_name"])
    if disk_public_key != public_key or disk_manifest != manifest:
        raise RuntimeError(PREF_translate("err_append_workspace_changed"))

    # O(1) sanity check on the current segment: it must exist, be a regular
    # file, and its size must not be smaller than the committed boundary.
    # We do NOT re-verify the chain contents here; that happens at open time.
    segment = manifest["segments"][-1]
    path = os.path.join(workspace, *segment["file"].split("/"))
    if os.path.islink(path) or not os.path.isfile(path):
        raise RuntimeError(PREF_translate("err_append_segment_missing"))
    if os.path.getsize(path) < segment["committed_offset"]:
        raise RuntimeError(PREF_translate("err_append_segment_missing"))

    # Link check: the new block must extend the exact chain the manifest
    # already commits to. This is the O(1) equivalent of the full-chain verify
    # for the *new* block.
    expected_number = manifest["next_operation_number"]
    previous_hash = manifest["last_chain_hash"]
    if block.get("operation_number") != expected_number:
        raise RuntimeError(PREF_translate("err_append_opnumber_mismatch"))
    if block.get("previous_chain_hash") != previous_hash:
        raise RuntimeError(PREF_translate("err_append_prev_hash_mismatch"))
    if not PREF_verify_block(
        block,
        previous_hash,
        public_key,
        manifest["program_hash"],
        manifest["runtime_fingerprint"],
    ):
        raise RuntimeError(PREF_translate("err_append_block_auth"))

    # Segment rollover when the current segment is full.
    if segment["rows"] >= PREF_MAX_ROWS_PER_SEGMENT:
        segment = PREF_create_next_segment(workspace, manifest)
        path = os.path.join(workspace, *segment["file"].split("/"))
        if os.path.islink(path) or not os.path.isfile(path):
            raise RuntimeError(PREF_translate("err_append_segment_missing"))

    line = PREF_serialize_block_line(block)
    flags = os.O_WRONLY | os.O_APPEND
    nofollow = getattr(os, "O_NOFOLLOW", 0)
    flags |= nofollow
    try:
        descriptor = os.open(path, flags)
        try:
            PREF_write_all_bytes(descriptor, line)
            os.fsync(descriptor)
        finally:
            os.close(descriptor)
    except OSError as exc:
        raise RuntimeError(PREF_translate("err_append_write_failed")) from exc

    segment["rows"] += 1
    segment["committed_offset"] += len(line)
    if segment["rows"] == PREF_MAX_ROWS_PER_SEGMENT:
        segment["sealed"] = True
        segment["sha256"] = PREF_hash_file_streaming(path)

    manifest["operation_count"] += 1
    manifest["next_operation_number"] += 1
    manifest["last_chain_hash"] = block["chain_hash"]
    signed_manifest = PREF_sign_manifest(manifest, seed)
    PREF_write_atomic(PREF_manifest_path(workspace), PREF_canonical_json(signed_manifest) + b"\n")
    manifest.clear()
    manifest.update(signed_manifest)

    # No post-append full-chain verify here. The next PREF_open_workspace call
    # is the authoritative integrity check. Removing this call turns the
    # commit path from O(n^2) to O(1) without weakening the security model,
    # because the new block was authenticated before the write and the
    # manifest is re-signed and atomically replaced after it.


def PREF_commit_operation(
    workspace: str,
    manifest: dict[str, Any],
    seed: bytes,
    public_key: bytes,
    operation_type: str,
    payload: dict[str, Any],
    started: datetime,
    ended: datetime,
) -> dict[str, Any]:
    """High-level universal commit API for business events, statements, and checkpoints."""
    if PREF_RUNTIME_IDENTITY is None:
        raise RuntimeError(PREF_translate("err_signer_missing_runtime"))
    block = PREF_build_block(
        manifest["next_operation_number"],
        started,
        ended,
        operation_type,
        payload,
        manifest["last_chain_hash"],
        PREF_RUNTIME_IDENTITY,
        seed,
    )
    PREF_append_block(workspace, manifest, seed, block, public_key)
    return block


def PREF_read_all_operations(workspace: str, manifest: dict[str, Any]) -> list[dict[str, Any]]:
    """Materialize the committed history only when explicitly requested by the caller."""
    operations: list[dict[str, Any]] = []
    for segment in manifest["segments"]:
        path = os.path.join(workspace, *segment["file"].split("/"))
        for block in PREF_iter_segment_blocks(path, segment["committed_offset"]):
            operations.append(block)
    if len(operations) != manifest["operation_count"]:
        raise RuntimeError(PREF_translate("err_dataset_read_all_count"))
    return operations


