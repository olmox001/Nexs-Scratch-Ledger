def PREF_trust_anchor_directory() -> str:
    """Return the absolute path of the trust-anchor directory.

    Resolution order:
      1. Process-local override (used only by the self-test suite).
      2. NEXS_TRUST_ANCHOR_DIR environment variable, if set (must be absolute).
      3. <program_dir>/trust_anchors.

    In hardened deployments, set NEXS_TRUST_ANCHOR_DIR to a location outside
    the program directory and outside the user's home (e.g. /etc/nexs/trust_anchors
    on POSIX, %PROGRAMDATA%\\Nexs\\trust_anchors on Windows) so that an
    attacker who controls the program directory cannot re-pin workspaces.
    """
    override = PREF_RUNTIME_TRUST_ANCHOR_DIRECTORY_OVERRIDE
    if override is not None:
        if not isinstance(override, str) or not override:
            raise RuntimeError(PREF_translate("err_anchor_dir_override"))
        if not os.path.isabs(override):
            raise RuntimeError(PREF_translate("err_anchor_dir_override_abs"))
        return override
    env_value = os.environ.get(PREF_TRUST_ANCHOR_ENV_VAR, "").strip()
    if env_value:
        if not os.path.isabs(env_value):
            raise RuntimeError(PREF_translate_format("err_anchor_env_abs", value=env_value))
        return env_value
    base_directory = os.path.dirname(os.path.realpath(os.path.abspath(__file__)))
    return os.path.join(base_directory, PREF_TRUST_ANCHOR_DIRECTORY_NAME)


def PREF_trust_anchor_path_for(logical_name: str) -> str:
    """Return the deterministic anchor file path for one logical workspace name."""
    if not PREF_validate_workspace_name(logical_name):
        raise ValueError(PREF_translate("err_workspace_name_invalid"))
    digest = PREF_sha256_text(PREF_normalize_workspace_name(logical_name))
    return os.path.join(
        PREF_trust_anchor_directory(),
        f"nxsl_{digest[:48]}.{PREF_TRUST_ANCHOR_EXTENSION}",
    )


def PREF_load_trust_anchors() -> dict[str, bytes]:
    """Load the pinned public keys from the trust anchor directory.

    Directory layout: trust_anchors/<digest>.anchor where each file is a JSON
    object:
        {"schema_version": 1,
         "workspace_name": "<original>",
         "public_key_ed25519": "<base64>",
         "created_utc": "<ISO-8601 timezone-aware>"}

    A missing directory means TOFU mode (empty mapping) unless
    NEXS_REQUIRE_ANCHOR is set, in which case the absence of the directory is a
    hard failure. Any structural, encoding, permission, or symlink problem
    inside the directory is always a hard failure: the trust anchor is the one
    component whose compromise would defeat the entire integrity model. Files
    are validated one by one and the whole load is aborted on the first
    invalid entry.
    """
    global PREF_RUNTIME_TRUST_ANCHORS
    directory = PREF_trust_anchor_directory()
    if not os.path.exists(directory):
        if PREF_explicit_anchor_required():
            raise RuntimeError(PREF_translate_format("err_anchor_dir_required", path=directory))
        PREF_RUNTIME_TRUST_ANCHORS = {}
        return {}
    if os.path.islink(directory) or not os.path.isdir(directory):
        raise RuntimeError(PREF_translate("err_anchor_dir_missing"))

    try:
        entries = sorted(os.scandir(directory), key=lambda item: item.name)
    except OSError as exc:
        raise RuntimeError(PREF_translate("err_anchor_dir_read")) from exc

    if len(entries) > PREF_MAX_TRUST_ANCHORS:
        raise RuntimeError(PREF_translate("err_anchor_too_many"))

    anchors: dict[str, bytes] = {}
    for entry in entries:
        if entry.name.startswith("."):
            continue
        if entry.is_symlink() or not entry.is_file(follow_symlinks=False):
            raise RuntimeError(PREF_translate_format("err_anchor_unsafe_entry", name=entry.name))
        if not entry.name.endswith(f".{PREF_TRUST_ANCHOR_EXTENSION}"):
            raise RuntimeError(PREF_translate_format("err_anchor_unexpected_file", name=entry.name))
        try:
            with open(entry.path, "rb") as source:
                raw = source.read(PREF_MAX_MANIFEST_BYTES + 1)
        except OSError as exc:
            raise RuntimeError(PREF_translate_format("err_anchor_read_failed", name=entry.name)) from exc
        if len(raw) > PREF_MAX_MANIFEST_BYTES:
            raise RuntimeError(PREF_translate_format("err_anchor_too_large", name=entry.name))
        try:
            data = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise RuntimeError(PREF_translate_format("err_anchor_invalid_json", name=entry.name)) from exc
        if not isinstance(data, dict):
            raise RuntimeError(PREF_translate_format("err_anchor_not_object", name=entry.name))
        required = {"schema_version", "workspace_name", "public_key_ed25519", "created_utc"}
        if not required <= set(data):
            raise RuntimeError(PREF_translate_format("err_anchor_missing_fields", name=entry.name))
        if data["schema_version"] != PREF_TRUST_ANCHOR_SCHEMA_VERSION:
            raise RuntimeError(PREF_translate_format("err_anchor_unsupported_schema", name=entry.name))
        name = data["workspace_name"]
        if not isinstance(name, str) or not PREF_validate_workspace_name(name):
            raise RuntimeError(PREF_translate_format("err_anchor_invalid_name", name=entry.name))
        try:
            public_key = PREF_base64_decode(data["public_key_ed25519"], 32)
        except (ValueError, TypeError) as exc:
            raise RuntimeError(PREF_translate_format("err_anchor_key_invalid", name=entry.name)) from exc
        try:
            created = datetime.fromisoformat(data["created_utc"])
        except (TypeError, ValueError) as exc:
            raise RuntimeError(PREF_translate_format("err_anchor_timestamp_invalid", name=entry.name)) from exc
        if created.tzinfo is None:
            raise RuntimeError(PREF_translate_format("err_anchor_timestamp_naive", name=entry.name))

        try:
            expected_name = os.path.basename(PREF_trust_anchor_path_for(name))
        except ValueError as exc:
            raise RuntimeError(PREF_translate_format("err_anchor_filename_mismatch", name=entry.name)) from exc
        if entry.name != expected_name:
            raise RuntimeError(PREF_translate_format("err_anchor_filename_mismatch", name=entry.name))

        normalized = PREF_normalize_workspace_name(name)
        if normalized in anchors:
            raise RuntimeError(PREF_translate_format("err_anchor_duplicate", name=name))
        anchors[normalized] = public_key

    PREF_RUNTIME_TRUST_ANCHORS = anchors
    return anchors


def PREF_persist_trust_anchor(logical_name: str, public_key: bytes) -> str:
    """Pin a workspace's public key by writing a new anchor file.

    Called at workspace creation time and when a temporary workspace is
    promoted. The written anchor is self-describing and can be copied, moved,
    deleted, or distributed independently. Returns the absolute path of the
    anchor file. The call is idempotent for the exact same (name, key) pair.
    """
    if not PREF_validate_workspace_name(logical_name):
        raise ValueError(PREF_translate("err_workspace_name_invalid"))
    if not isinstance(public_key, bytes) or len(public_key) != 32:
        raise ValueError(PREF_translate("err_public_key_invalid"))

    directory = PREF_trust_anchor_directory()
    if os.path.lexists(directory):
        if os.path.islink(directory) or not os.path.isdir(directory):
            raise RuntimeError(PREF_translate("err_anchor_dir_unsafe"))
    else:
        try:
            os.makedirs(directory, mode=0o700 if os.name != "nt" else 0o777)
        except OSError as exc:
            raise RuntimeError(PREF_translate("err_anchor_mkdir")) from exc
        if os.name != "nt":
            try:
                PREF_sync_directory(os.path.dirname(directory))
            except RuntimeError:
                pass

    target = PREF_trust_anchor_path_for(logical_name)
    if os.path.lexists(target):
        # Idempotent: if the same key is already pinned, do nothing.
        existing_doc: Any = None
        try:
            with open(target, "rb") as source:
                existing_doc = json.loads(source.read(PREF_MAX_MANIFEST_BYTES).decode("utf-8"))
        except (OSError, ValueError, json.JSONDecodeError):
            existing_doc = None
        if (
            isinstance(existing_doc, dict)
            and existing_doc.get("workspace_name") == PREF_normalize_workspace_name(logical_name)
            and existing_doc.get("public_key_ed25519") == PREF_base64_encode(public_key)
        ):
            return target
        if isinstance(existing_doc, dict) and existing_doc.get("workspace_name") == PREF_normalize_workspace_name(logical_name):
            raise RuntimeError(PREF_translate("err_anchor_exists_diff_key"))
        raise RuntimeError(PREF_translate("err_anchor_exists_invalid"))

    anchor = {
        "schema_version": PREF_TRUST_ANCHOR_SCHEMA_VERSION,
        "workspace_name": PREF_normalize_workspace_name(logical_name),
        "public_key_ed25519": PREF_base64_encode(public_key),
        "created_utc": datetime.now(timezone.utc).isoformat(),
    }
    PREF_write_atomic(target, PREF_canonical_json(anchor) + b"\n")
    PREF_set_private_permissions(target)
    return target


def PREF_enforce_trust_anchor(logical_name: str, public_key: bytes) -> str:
    """Enforce the pinned public key when a trust anchor entry exists.

    Returns:
      - "pinned_ok"     : an anchor exists for this workspace and it matches.
      - "unpinned"      : no anchor exists for this workspace (TOFU mode).

    Raises RuntimeError when an anchor exists but the manifest public key does
    not match, or when NEXS_REQUIRE_ANCHOR is set and no anchor is available.
    """
    if not isinstance(logical_name, str) or not isinstance(public_key, bytes) or len(public_key) != 32:
        raise ValueError(PREF_translate("err_anchor_enforce_args"))
    anchors = PREF_RUNTIME_TRUST_ANCHORS
    if anchors is None:
        anchors = PREF_load_trust_anchors()
    pinned = anchors.get(PREF_normalize_workspace_name(logical_name))
    if pinned is None:
        if PREF_explicit_anchor_required():
            raise RuntimeError(PREF_translate("trust_anchor_required_missing"))
        return "unpinned"
    if not PREF_secure_compare_bytes(pinned, public_key):
        raise RuntimeError(PREF_translate("err_anchor_mismatch"))
    return "pinned_ok"


