def PREF_build_block(
    operation_number: int,
    started_utc: datetime,
    ended_utc: datetime,
    operation_type: str,
    payload: dict[str, Any],
    previous_chain_hash: str,
    identity: dict[str, Any],
    seed: bytes,
) -> dict[str, Any]:
    """Build exactly one signed canonical block."""
    if type(operation_number) is not int or operation_number < 1:
        raise ValueError(PREF_translate("err_block_operation_number"))
    if not isinstance(operation_type, str) or not operation_type.strip() or len(operation_type) > PREF_MAX_OPERATION_TYPE_CHARS:
        raise ValueError(PREF_translate("err_block_operation_type"))
    for label, value in (("program_hash", identity["program_hash"]), ("runtime_fingerprint", identity["runtime_fingerprint"]), ("previous_chain_hash", previous_chain_hash)):
        if not isinstance(value, str) or len(value) != 64:
            raise ValueError(PREF_translate_format("err_block_hash_field", label=label))
        try:
            bytes.fromhex(value)
        except ValueError as exc:
            raise ValueError(PREF_translate_format("err_block_hash_field", label=label)) from exc
    if not isinstance(seed, bytes) or len(seed) != 32:
        raise ValueError(PREF_translate("err_block_seed"))
    if not isinstance(started_utc, datetime) or not isinstance(ended_utc, datetime):
        raise TypeError(PREF_translate("err_block_timestamps"))
    start = started_utc.astimezone(timezone.utc)
    end = ended_utc.astimezone(timezone.utc)
    if end < start:
        raise ValueError(PREF_translate("err_block_end_before_start"))
    if not isinstance(payload, dict):
        raise TypeError(PREF_translate("err_block_payload"))
    PREF_require_json_value(payload)

    body = {
        "schema_version": PREF_SCHEMA_VERSION,
        "program_hash": identity["program_hash"],
        "runtime_fingerprint": identity["runtime_fingerprint"],
        "operation_number": operation_number,
        "started_utc": start.isoformat(),
        "ended_utc": end.isoformat(),
        "operation_type": operation_type.strip(),
        "payload": payload,
        "previous_chain_hash": previous_chain_hash,
    }
    block_hash = PREF_sha256_bytes(PREF_canonical_json(body))
    chain_hash = PREF_sha256_text(previous_chain_hash + block_hash)
    signed = dict(body)
    signed["block_hash"] = block_hash
    signed["chain_hash"] = chain_hash
    signed["signature"] = PREF_sign_bytes(seed, PREF_canonical_json(signed))
    PREF_serialize_block_line(signed)
    return signed


def PREF_verify_block(
    block: dict[str, Any],
    expected_previous_hash: str,
    expected_public_key: bytes,
    expected_program_hash: str | None = None,
    expected_runtime_fingerprint: str | None = None,
) -> bool:
    """Verify exact block structure, hashes, timestamps, and Ed25519 signature."""
    required = {
        "schema_version", "program_hash", "runtime_fingerprint", "operation_number",
        "started_utc", "ended_utc", "operation_type", "payload",
        "previous_chain_hash", "block_hash", "chain_hash", "signature",
    }
    if not isinstance(block, dict) or set(block) != required:
        return False
    if block["schema_version"] != PREF_SCHEMA_VERSION:
        return False
    if expected_program_hash is not None and block["program_hash"] != expected_program_hash:
        return False
    if expected_runtime_fingerprint is not None and block["runtime_fingerprint"] != expected_runtime_fingerprint:
        return False
    if block["previous_chain_hash"] != expected_previous_hash:
        return False
    if type(block["operation_number"]) is not int or block["operation_number"] < 1:
        return False
    if not isinstance(block["operation_type"], str) or not block["operation_type"] or len(block["operation_type"]) > PREF_MAX_OPERATION_TYPE_CHARS:
        return False
    if not isinstance(block["payload"], dict):
        return False
    try:
        for field in ("program_hash", "runtime_fingerprint", "previous_chain_hash", "block_hash", "chain_hash"):
            if not isinstance(block[field], str) or len(block[field]) != 64:
                return False
            bytes.fromhex(block[field])
        started = datetime.fromisoformat(block["started_utc"])
        ended = datetime.fromisoformat(block["ended_utc"])
        if started.tzinfo is None or ended.tzinfo is None or ended < started:
            return False
        PREF_require_json_value(block["payload"])
        PREF_canonical_json(block)
    except (ValueError, TypeError, OverflowError, RecursionError):
        return False

    body = {key: block[key] for key in (
        "schema_version", "program_hash", "runtime_fingerprint", "operation_number",
        "started_utc", "ended_utc", "operation_type", "payload", "previous_chain_hash"
    )}
    recalculated_block_hash = PREF_sha256_bytes(PREF_canonical_json(body))
    if not PREF_secure_compare(recalculated_block_hash, block["block_hash"]):
        return False
    recalculated_chain_hash = PREF_sha256_text(block["previous_chain_hash"] + recalculated_block_hash)
    if not PREF_secure_compare(recalculated_chain_hash, block["chain_hash"]):
        return False

    signature_body = dict(block)
    signature = signature_body.pop("signature")
    return PREF_verify_signature(expected_public_key, PREF_canonical_json(signature_body), signature)


def PREF_serialize_block_line(block: dict[str, Any]) -> bytes:
    """Serialize a block as one bounded JSON line.

    PREF_MAX_BLOCK_BYTES is enforced as the total size of the serialized line
    *including* the trailing newline, so the writer and PREF_iter_segment_blocks
    agree exactly on the maximum accepted size.
    """
    raw = PREF_canonical_json(block)
    if len(raw) + 1 > PREF_MAX_BLOCK_BYTES:
        raise RuntimeError(PREF_translate("err_block_too_large"))
    return raw + b"\n"


def PREF_iter_segment_blocks(path: str, max_bytes: int | None = None) -> Iterator[dict[str, Any]]:
    """Yield strictly framed blocks; every committed line must end with a newline."""
    if os.path.islink(path) or not os.path.isfile(path):
        raise RuntimeError(PREF_translate_format("err_chain_segment_missing", path=path))
    limit = os.path.getsize(path) if max_bytes is None else max_bytes
    if limit < 0:
        raise ValueError(PREF_translate("err_segment_limit_negative"))
    consumed = 0
    try:
        with open(path, "rb") as source:
            line_number = 0
            while consumed < limit:
                raw_line = source.readline(PREF_MAX_BLOCK_BYTES + 1)
                if not raw_line:
                    break
                line_number += 1
                consumed += len(raw_line)
                if len(raw_line) > PREF_MAX_BLOCK_BYTES:
                    raise RuntimeError(PREF_translate("err_segment_oversized_block"))
                if consumed > limit:
                    raise RuntimeError(PREF_translate("err_append_boundary_cut"))
                if not raw_line.endswith(b"\n") or not raw_line.strip():
                    raise RuntimeError(PREF_translate("err_segment_line_terminator"))
                try:
                    block = json.loads(raw_line[:-1].decode("utf-8"))
                except (UnicodeDecodeError, json.JSONDecodeError) as exc:
                    raise RuntimeError(PREF_translate_format("err_segment_invalid_json", line=line_number)) from exc
                if not isinstance(block, dict):
                    raise RuntimeError(PREF_translate_format("err_segment_line_not_object", line=line_number))
                PREF_require_json_value(block)
                yield block
            if consumed != limit:
                raise RuntimeError(PREF_translate("err_segment_boundary_mismatch"))
            if line_number > PREF_MAX_ROWS_PER_SEGMENT:
                raise RuntimeError(PREF_translate("err_segment_row_limit"))
    except OSError as exc:
        raise RuntimeError(PREF_translate_format("err_segment_read", path=path)) from exc


def PREF_read_segment_blocks(path: str, committed_offset: int | None = None) -> list[dict[str, Any]]:
    """Materialize a segment, optionally restricted to its committed byte boundary."""
    return list(PREF_iter_segment_blocks(path, committed_offset))


def PREF_verify_full_chain(workspace: str, manifest: dict[str, Any], public_key: bytes) -> int:
    """Verify every committed byte, block, segment boundary, and final chain state."""
    PREF_validate_manifest_structure(manifest, manifest["logical_name"])
    if PREF_base64_encode(public_key) != manifest["public_key_ed25519"]:
        raise RuntimeError(PREF_translate("err_manifest_verify_key"))

    previous_hash = PREF_GENESIS_HASH
    expected_number = 1
    verified_count = 0
    for segment in manifest["segments"]:
        path = os.path.join(workspace, *segment["file"].split("/"))
        if os.path.islink(path) or not os.path.isfile(path):
            raise RuntimeError(PREF_translate_format("err_chain_segment_missing", path=path))
        actual_size = os.path.getsize(path)
        committed_offset = segment["committed_offset"]
        if actual_size < committed_offset:
            raise RuntimeError(PREF_translate_format("err_chain_segment_shorter", path=path))
        if segment["sealed"] and actual_size != committed_offset:
            raise RuntimeError(PREF_translate_format("err_chain_sealed_has_extra", path=path))
        row_count = 0
        for block in PREF_iter_segment_blocks(path, committed_offset):
            row_count += 1
            if block.get("program_hash") != manifest["program_hash"]:
                raise RuntimeError(PREF_translate("err_chain_block_program_hash"))
            if block.get("runtime_fingerprint") != manifest["runtime_fingerprint"]:
                raise RuntimeError(PREF_translate("err_chain_block_runtime_fp"))
            if block.get("operation_number") != expected_number:
                raise RuntimeError(PREF_translate("err_chain_block_numbering"))
            if not PREF_verify_block(
                block,
                previous_hash,
                public_key,
                manifest["program_hash"],
                manifest["runtime_fingerprint"],
            ):
                raise RuntimeError(PREF_translate_format("err_chain_block_verify", number=expected_number))
            previous_hash = block["chain_hash"]
            expected_number += 1
            verified_count += 1
        if row_count != segment["rows"]:
            raise RuntimeError(PREF_translate_format("err_chain_seg_row_mismatch", file=segment["file"]))
        if segment["sealed"]:
            actual_hash = PREF_hash_file_streaming(path)
            if not PREF_secure_compare(actual_hash, segment["sha256"]):
                raise RuntimeError(PREF_translate_format("err_chain_sealed_hash", file=segment["file"]))

    if previous_hash != manifest["last_chain_hash"]:
        raise RuntimeError(PREF_translate("err_chain_final_hash"))
    if verified_count != manifest["operation_count"]:
        raise RuntimeError(PREF_translate("err_chain_opcount"))
    return verified_count


