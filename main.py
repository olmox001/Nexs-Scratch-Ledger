def PREF_prompt_age() -> int:
    """Read and validate an integer age within the range accepted by the calculator.

    The accepted range is PREF_MIN_ACCEPTED_AGE..PREF_MAX_ACCEPTED_AGE, aligned
    with PREF_calculate_discount_payload, which rejects ages >= 160 as
    implausible. Values outside this range are rejected at input time with a
    localized message rather than aborting the session later.
    """
    for _attempt in range(PREF_MAX_INPUT_ATTEMPTS):
        try:
            raw = PREF_input(PREF_translate("age_prompt")).strip()
        except EOFError as exc:
            raise RuntimeError(PREF_translate("err_input_age_eof")) from exc
        try:
            value = int(raw)
        except ValueError:
            PREF_print(PREF_translate("input_integer_invalid"))
            continue
        if value < PREF_MIN_ACCEPTED_AGE or value > PREF_MAX_ACCEPTED_AGE:
            PREF_print(PREF_translate("age_invalid"))
            continue
        return value
    raise RuntimeError(PREF_translate("err_input_age_limit"))


def PREF_confirm(translation_key: str) -> bool:
    """Read a localized yes/no response."""
    yes = PREF_translate("yes").casefold()
    no = PREF_translate("no").casefold()
    for _attempt in range(PREF_MAX_INPUT_ATTEMPTS):
        try:
            answer = PREF_input(PREF_translate(translation_key)).strip().casefold()
        except EOFError as exc:
            raise RuntimeError(PREF_translate("err_input_confirm_eof")) from exc
        if answer == yes:
            return True
        if answer == no:
            return False
        PREF_print(PREF_translate("yes_or_no_invalid"))
    raise RuntimeError(PREF_translate("err_input_confirm_limit"))


def PREF_calculate_discount_payload(
    price: Decimal,
    age: int,
    base_discount_percent: int,
    calculation_time: datetime,
) -> dict[str, Any]:
    """Compute the demonstration discount without redundant aliases of the final price.

    The age range validated here must stay aligned with PREF_prompt_age and
    PREF_MAX_ACCEPTED_AGE. If a caller bypasses the prompt and supplies an
    out-of-range age, this function still fails closed with ValueError, but the
    normal UI path never reaches that state.
    """
    if age < PREF_MIN_ACCEPTED_AGE or age > PREF_MAX_ACCEPTED_AGE:
        raise ValueError(PREF_translate("age_invalid"))
    age_case = PREF_calculate_age_case(age)
    date_case = PREF_calculate_date_case(calculation_time)
    age_bonus = {0: 0, 1: 15, 2: 10, 3: 15, 4: 0}[age_case]
    date_bonus = {0: 0, 1: 5, 2: 5, 3: 10}[date_case]

    if age_case == 1:
        PREF_print(PREF_translate("age_case_child"))
    elif age_case == 2:
        PREF_print(PREF_translate("age_case_teen"))
    elif age_case == 3:
        PREF_print(PREF_translate("age_case_senior"))
    elif age_case == 4:
        PREF_print(PREF_translate("age_case_implausible"))
        raise ValueError(PREF_translate("age_case_implausible"))

    if date_case == 1:
        PREF_print(PREF_translate("date_case_sunday"))
    elif date_case == 2:
        PREF_print(PREF_translate("date_case_december"))
    elif date_case == 3:
        PREF_print(PREF_translate("date_case_sunday_december"))

    total_percent = min(100, base_discount_percent + age_bonus + date_bonus)
    discount_amount = (price * Decimal(total_percent) / Decimal(100)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    final_price = (price - discount_amount).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)

    # Only one persisted field represents the final price: final_price_cents.
    return {
        "price_cents": int((price * 100).to_integral_value(rounding=ROUND_HALF_UP)),
        "age": age,
        "base_discount_percent": base_discount_percent,
        "age_case": age_case,
        "date_case": date_case,
        "discount_percent": total_percent,
        "discount_amount_cents": int((discount_amount * 100).to_integral_value(rounding=ROUND_HALF_UP)),
        "final_price_cents": int((final_price * 100).to_integral_value(rounding=ROUND_HALF_UP)),
    }


