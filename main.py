def PREF_set_language(language_code: str) -> None:
    """Set the active language only when the code exists."""
    global PREF_ACTIVE_LANGUAGE
    if language_code in PREF_TRANSLATIONS:
        PREF_ACTIVE_LANGUAGE = language_code


def PREF_translate(key: str) -> str:
    """Resolve a UI key with deterministic English fallback."""
    active = PREF_TRANSLATIONS.get(PREF_ACTIVE_LANGUAGE, {})
    text = active.get(key)
    if text is not None:
        return text
    return PREF_TRANSLATIONS["eng"].get(key, f"[[MISSING:{key}]]")


