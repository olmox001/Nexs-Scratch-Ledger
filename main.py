def PREF_copy_workspace_atomically(
    source_workspace: str,
    logical_name: str,
    destination_directory: str,
    signing_seed: bytes | None = None,
) -> str:
    """Promote a verified temporary workspace, optionally signing a logical-name rename."""
    if not isinstance(source_workspace, str) or not source_workspace or os.path.islink(source_workspace):
        raise RuntimeError(PREF_translate("err_copy_source_unsafe"))
    source_real = os.path.realpath(source_workspace)
    normalized_name = PREF_normalize_workspace_name(logical_name)
    destination = PREF_workspace_path(normalized_name, destination_directory)
    if os.path.lexists(destination):
        raise FileExistsError(destination)
    PREF_safe_workspace_directory(source_real)
    source_logical = PREF_scan_workspace_logical_name(source_real)
    manifest, public_key = PREF_load_manifest(source_real, source_logical)
    PREF_verify_full_chain(source_real, manifest, public_key)

    if not isinstance(signing_seed, bytes) or len(signing_seed) != 32:
        raise RuntimeError(PREF_translate("err_copy_seed_required"))
    if not PREF_secure_compare_bytes(PREF_public_key_from_seed(signing_seed), public_key):
        raise RuntimeError(PREF_translate("err_copy_seed_mismatch"))
    if normalized_name != manifest["logical_name"]:
        manifest = dict(manifest)
        manifest["logical_name"] = normalized_name
        manifest = PREF_sign_manifest(manifest, signing_seed)

    parent = os.path.abspath(destination_directory)
    if os.path.islink(parent):
        raise RuntimeError(PREF_translate("err_copy_dest_symlink"))
    os.makedirs(parent, exist_ok=True)
    staging_destination = os.path.join(
        parent,
        f".{os.path.basename(destination)}.{secrets.token_hex(16)}.tmp",
    )
    try:
        os.makedirs(staging_destination, mode=0o700 if os.name != "nt" else 0o777)
        os.makedirs(os.path.join(staging_destination, PREF_SEGMENT_DIRECTORY), exist_ok=False)
        os.makedirs(os.path.join(staging_destination, PREF_STAGING_DIRECTORY), exist_ok=False)
        PREF_write_atomic(
            PREF_manifest_path(staging_destination),
            PREF_canonical_json(manifest) + b"\n",
        )
        for segment in manifest["segments"]:
            source_path = os.path.join(source_real, *segment["file"].split("/"))
            destination_path = os.path.join(staging_destination, *segment["file"].split("/"))
            if os.path.islink(source_path) or not os.path.isfile(source_path):
                raise RuntimeError(PREF_translate("err_copy_seg_unsafe"))
            shutil.copy2(source_path, destination_path)
        PREF_set_private_permissions(PREF_manifest_path(staging_destination))
        for segment in manifest["segments"]:
            PREF_set_private_permissions(os.path.join(staging_destination, *segment["file"].split("/")))
        PREF_sync_directory(os.path.join(staging_destination, PREF_SEGMENT_DIRECTORY))
        PREF_sync_directory(staging_destination)
        if os.path.exists(destination):
            raise FileExistsError(destination)
        os.replace(staging_destination, destination)
        PREF_sync_directory(parent)
    except (OSError, RuntimeError, ValueError, TypeError, KeyError):
        shutil.rmtree(staging_destination, ignore_errors=True)
        raise

    # Workspace promotion is complete: persist a trust anchor for the new
    # logical name so the promoted workspace is pinned from the moment it
    # becomes permanent. Anchor persistence is best-effort and never rolled
    # back — the workspace itself is already valid.
    try:
        anchor_path = PREF_persist_trust_anchor(normalized_name, public_key)
        PREF_print_message("trust_anchor_created", anchor_path)
    except (OSError, RuntimeError, ValueError, TypeError) as exc:
        if PREF_explicit_anchor_required():
            raise RuntimeError(PREF_translate_format("err_anchor_persist_promote", detail=exc)) from exc
        PREF_print_message("trust_anchor_persist_failed", exc)
    return destination


def PREF_save_temporary_workspace(source_workspace: str) -> None:
    """Optionally promote a temporary workspace to a permanent named workspace."""
    if not PREF_confirm("save_temporary_question"):
        PREF_print(PREF_translate("workspace_not_saved"))
        shutil.rmtree(source_workspace, ignore_errors=True)
        return

    for _attempt in range(PREF_MAX_INPUT_ATTEMPTS):
        try:
            logical_name = PREF_normalize_workspace_name(PREF_input(PREF_translate("save_temporary_name")))
        except EOFError as exc:
            raise RuntimeError(PREF_translate("err_save_eof")) from exc
        if not PREF_validate_workspace_name(logical_name):
            PREF_print(PREF_translate("workspace_invalid_name"))
            continue
        try:
            signing_seed: bytes | None = None
            if PREF_RUNTIME_CREDENTIALS is not None:
                manifest, _public_key = PREF_load_manifest(
                    source_workspace, PREF_scan_workspace_logical_name(source_workspace)
                )
                signing_seed = PREF_derive_private_seed(
                    PREF_RUNTIME_CREDENTIALS["username"],
                    PREF_RUNTIME_CREDENTIALS["password"],
                    manifest["program_hash"],
                )
            destination = PREF_copy_workspace_atomically(
                source_workspace, logical_name, os.path.abspath("."), signing_seed
            )
            PREF_print(PREF_translate("saved_successfully"), destination)
            shutil.rmtree(source_workspace, ignore_errors=True)
            return
        except FileExistsError:
            PREF_print(PREF_translate("workspace_exists"))
        except OSError as exc:
            PREF_print(PREF_translate_format("err_save_failed", detail=exc))
            return
    raise RuntimeError(PREF_translate("err_save_limit"))


